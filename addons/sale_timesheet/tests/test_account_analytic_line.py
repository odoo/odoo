from odoo.tests import tagged

from odoo.addons.sale_timesheet.tests.common import TestCommonSaleTimesheet


@tagged('-at_install', 'post_install')
class TestAccountAnalyticLine(TestCommonSaleTimesheet):

    _test_user_groups = None  # FIXME list needed groups

    def test_timesheet_product_from_sale_line(self):
        sale_line = self.so.order_line.filtered(lambda sol: sol.product_id == self.product_delivery_timesheet2)
        task = self.env['project.task'].search([('sale_line_id', '=', sale_line.id)])
        timesheet = self.env['account.analytic.line'].create({
            'name': 'Timesheet',
            'project_id': task.project_id.id,
            'task_id': task.id,
            'unit_amount': 3,
            'employee_id': self.employee_user.id,
        })

        self.assertEqual(timesheet.so_line, sale_line)
        self.assertEqual(
            timesheet.product_id, self.product_delivery_timesheet2,
            "The product of the timesheet should be the one of its sales order item.")
        self.assertEqual(
            timesheet.product_uom_id, self.env.company.project_time_mode_id,
            "The timesheet should still be encoded in the time unit of the company.")

        other_sale_line = self.so.order_line.filtered(lambda sol: sol.product_id == self.product_delivery_timesheet1)
        timesheet.so_line = other_sale_line
        self.assertEqual(
            timesheet.product_id, self.product_delivery_timesheet1,
            "The product of the timesheet should follow its sales order item.")

    def test_timesheet_product_without_sale_line(self):
        timesheet = self.env['account.analytic.line'].create({
            'name': 'Timesheet',
            'project_id': self.project_non_billable.id,
            'unit_amount': 3,
            'employee_id': self.employee_user.id,
        })

        self.assertFalse(timesheet.so_line)
        self.assertFalse(
            timesheet.product_id,
            "A non-billable timesheet should have no product.")

    def test_invoice_analytic_line_so_line(self):
        sale_order = self.env['sale.order'].create({
            'partner_id': self.partner_b.id,
            'order_line': [(0, 0, {
                'product_id': self.product_order_timesheet2.id,
                'product_uom_qty': 4,
            })],
        })
        sale_order.action_confirm()

        invoice = sale_order._create_invoices()
        invoice.action_post()

        analytic_lines = invoice.invoice_line_ids.analytic_line_ids
        self.assertTrue(analytic_lines, "Posting the invoice should generate analytic lines.")
        self.assertEqual(
            analytic_lines.so_line, sale_order.order_line,
            "The analytic lines generated by the invoice should be linked to the invoiced sales order item.")

    def test_credit_note_analytic_line_has_no_so_line(self):
        product = self.env['product.product'].create({
            'name': 'Reinvoiceable service',
            'type': 'service',
            'invoice_policy': 'order',
            'service_type': 'manual',
            'reinvoice_policy': 'sales_price',
            'list_price': 100.0,
            'taxes_id': False,
        })
        sale_order = self.env['sale.order'].create({
            'partner_id': self.partner_b.id,
            'order_line': [(0, 0, {
                'product_id': product.id,
                'product_uom_qty': 10,
                'analytic_distribution': {str(self.analytic_account_sale.id): 100},
            })],
        })
        sale_order.action_confirm()
        sale_line = sale_order.order_line
        self.assertEqual(sale_line.qty_delivered_method, 'analytic')

        invoice = sale_order._create_invoices()
        invoice.action_post()
        self.assertEqual(invoice.invoice_line_ids.analytic_line_ids.so_line, sale_line)
        self.assertEqual(
            sale_line.qty_delivered, 0.0,
            "Invoicing an ordered quantity should not deliver it.")

        credit_note = invoice._reverse_moves([{'invoice_date': invoice.invoice_date}])
        credit_note.action_post()

        self.assertFalse(
            credit_note.invoice_line_ids.analytic_line_ids.so_line,
            "The analytic lines of a credit note should not be linked to a sales order item, "
            "otherwise their negative amount is counted as a delivered quantity.")
        self.assertEqual(
            sale_line.qty_delivered, 0.0,
            "A credit note should not increase the delivered quantity.")

    def test_negative_invoice_line_analytic_line_has_no_so_line(self):
        product = self.env['product.product'].create({
            'name': 'Reinvoiceable service',
            'type': 'service',
            'invoice_policy': 'order',
            'service_type': 'manual',
            'reinvoice_policy': 'sales_price',
            'list_price': 100.0,
            'taxes_id': False,
        })
        distribution = {str(self.analytic_account_sale.id): 100}
        sale_order = self.env['sale.order'].create({
            'partner_id': self.partner_b.id,
            'order_line': [
                (0, 0, {
                    'product_id': product.id,
                    'product_uom_qty': 10,
                    'price_unit': 100.0,
                    'analytic_distribution': distribution,
                }),
                (0, 0, {
                    'product_id': product.id,
                    'product_uom_qty': 10,
                    'price_unit': -100.0,
                    'analytic_distribution': distribution,
                }),
            ],
        })
        sale_order.action_confirm()
        invoiced_line, discount_line = sale_order.order_line

        invoice = sale_order._create_invoices()
        invoice.action_post()

        self.assertEqual(invoiced_line.analytic_line_ids.so_line, invoiced_line)
        self.assertFalse(
            discount_line.analytic_line_ids.so_line,
            "The analytic line of a negative invoice line should not be linked to a sales order "
            "item, otherwise its negative amount is counted as a delivered quantity.")
        self.assertEqual(
            (invoiced_line.qty_delivered, discount_line.qty_delivered), (0.0, 0.0),
            "Invoicing ordered quantities should not deliver them.")
