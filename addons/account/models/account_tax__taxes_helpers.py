    @api.model
    def _init_taxes_engine_base_line_batches(self, global_context, base_line):
        tax_details = base_line['tax_details']
        evaluation_context = tax_details['_evaluation_context']

        batches = self._batch_taxes_per_computation_base(base_line)
        tax_details['_batches'] = batches
        for i, batch in enumerate(batches):
            batch['_evaluation_context'] = evaluation_context
            batch['_base_line'] = base_line
            for tax_data in batch['taxes_data']:
                tax_data['_batch'] = batch

        # Chain the batches together.
        for i, batch in enumerate(batches):
            subsequent_taxes_data = []
            if batch['include_base_amount']:
                for other_batch in batches[i + 1:]:
                    for other_tax_data in other_batch['taxes_data']:
                        if not other_tax_data['is_reverse_charge']:
                            subsequent_taxes_data.append(other_tax_data)
            for tax_data in batch['taxes_data']:
                tax_data['subsequent_taxes_data'] = subsequent_taxes_data

    @api.model
    def _init_taxes_engine_base_line_taxes_data(self, global_context, base_line):
        taxes_data_per_grouping_key = global_context['taxes_data_per_grouping_key']

        tax_details = base_line['tax_details']
        taxes_data = tax_details['taxes_data']
        evaluation_context = tax_details['_evaluation_context']
        group_per_tax = evaluation_context['group_per_tax']
        sorted_taxes = evaluation_context['sorted_taxes']

        for tax in sorted_taxes:
            common_tax_data_grouping_key = self._get_base_line_tax_data_grouping_key(global_context, base_line, tax)

            raw_tax_data_grouping_key = frozendict({**common_tax_data_grouping_key, 'is_reverse_charge': False})
            tax_data_grouping_key = frozendict(raw_tax_data_grouping_key)
            tax_data = {
                'tax': tax,
                'group': group_per_tax.get(tax.id) or self.env['account.tax'],
                'price_include': tax_data_grouping_key['price_include'],
                'original_price_include': tax_data_grouping_key['original_price_include'],
                'is_reverse_charge': tax_data_grouping_key['is_reverse_charge'],

                '_base_line': base_line,
                '_grouping_key': tax_data_grouping_key,
            }
            taxes_data.append(tax_data)
            taxes_data_per_grouping_key.setdefault(tax_data_grouping_key, []).append(tax_data)

            if tax.has_negative_factor:
                raw_tax_data_grouping_key = frozendict({**common_tax_data_grouping_key, 'is_reverse_charge': True})
                tax_data_grouping_key = frozendict(raw_tax_data_grouping_key)
                reverse_charge_tax_data = {
                    **tax_data,
                    'price_include': tax_data_grouping_key['price_include'],
                    'original_price_include': tax_data_grouping_key['original_price_include'],
                    'is_reverse_charge': tax_data_grouping_key['is_reverse_charge'],
                    'related_tax_data': tax_data,
                    '_grouping_key': tax_data_grouping_key,
                }
                taxes_data.append(reverse_charge_tax_data)
                taxes_data_per_grouping_key.setdefault(tax_data_grouping_key, []).append(reverse_charge_tax_data)

    @api.model
    def _init_taxes_engine_base_lines(self, global_context):
        base_lines = global_context['base_lines']
        base_lines_per_grouping_key = global_context['base_lines_per_grouping_key']

        for i, base_line in enumerate(base_lines):
            # Define how the base lines will be combine together to compute the
            # total excluded amount.
            base_lines_grouping_key = frozendict(self._get_base_line_grouping_key(global_context, base_line))

            # Sort the taxes and keep track of the parent group of taxes.
            sorted_taxes, group_per_tax = base_line['tax_ids']._flatten_taxes_and_sort_them()
            if filter_tax_function := base_line['filter_tax_function']:
                sorted_taxes = sorted_taxes.filtered(filter_tax_function)

            # The context defining what you have access to compute the tax amount.
            evaluation_context = {
                'sorted_taxes': sorted_taxes,
                'group_per_tax': group_per_tax,
                'product': sorted_taxes._eval_taxes_computation_turn_to_product_values(product=base_line['product_id']),
                'uom': sorted_taxes._eval_taxes_computation_turn_to_product_uom_values(product_uom=base_line['product_uom_id']),
                'rate': base_line['rate'],
                'price_unit': base_line['price_unit'],
                'quantity': base_line['quantity'],
                'discount': base_line['discount'],
                'raw_base': base_line['price_unit'] * base_line['quantity'] * (1 - (base_line['discount'] / 100.0)),
            }

            base_line['tax_details'] = {
                'taxes_data': [],
                '_grouping_key': base_lines_grouping_key,
                '_evaluation_context': evaluation_context,
            }
            base_lines_per_grouping_key.setdefault(base_lines_grouping_key, []).append(base_line)

            self._init_taxes_engine_base_line_taxes_data(global_context, base_line)
            self._init_taxes_engine_base_line_batches(global_context, base_line)

