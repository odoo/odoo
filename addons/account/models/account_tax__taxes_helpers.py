    @api.model
    def _get_raw_tax_amount_currency(self, batch, tax_data, base, fix_rate=1.0):
        """ Compute the tax amount for a specific tax.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param batch:       The current batch that is evaluated (see '_batch_taxes_per_computation_base').
        :param tax_data:    The current tax_data inside the batch that is evaluated.
        :param base:        The computation base. Typically, it's the computation base (price_unit * quantity * (1 - discount))
                            plus or minus the taxes affecting the base of the current batch.
                            Therefore, it's the base on which we have to compute the tax amount.
                            Since this method is called in both the price-excluded and price-included cases,
                            using it is probably a bad idea in this method.
        :param fix_rate:    For taxes that doesn't scale based on the 'base' passed as parameter, we have to multiply the
                            result by 'fix_rate' that might be different of 1.0 when the taxes engine is computed using the currency
                            of the company instead of the foreign one.
                            In others words, when computed in company currency, 'fix_rate' contains the rate between the foreign currency
                            and the national currency.
        :return:            The raw tax amount for this tax.
        """
        evaluation_context = batch['_evaluation_context']
        base_line = batch['_base_line']

        if base_line['special_type'] == 'non_deductible' and tax_data['is_reverse_charge']:
            tax_data['skip'] = True
            return 0.0

        if tax_data['is_reverse_charge']:
            return -tax_data['related_tax_data']['raw_tax_amount_currency'].value()

        tax = tax_data['tax']
        if tax.amount_type == 'fixed':
            sign = -1 if evaluation_context['price_unit'] < 0.0 else 1
            return sign * evaluation_context['quantity'] * tax.amount * fix_rate

    @api.model
    def _get_price_excluded_raw_tax_amount_currency(self, batch, tax_data, base_untaxed, fix_rate=1.0):
        """ Compute the tax amount for a specific tax in the price-excluded context.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param batch:           The current batch that is evaluated (see '_batch_taxes_per_computation_base').
        :param tax_data:        The current tax_data inside the batch that is evaluated.
        :param base_untaxed:    The computation base without tax (price_unit * quantity * (1 - discount))
                                plus or minus the taxes affecting the base of the current batch
                                on which we have to compute the tax amount.
        :param fix_rate:        For taxes that doesn't scale based on the 'base' passed as parameter, we have to multiply the
                                result by 'fix_rate' that might be different of 1.0 when the taxes engine is computed using the currency
                                of the company instead of the foreign one.
                                In others words, when computed in company currency, 'fix_rate' contains the rate between the foreign currency
                                and the national currency.
        :return:                The raw tax amount for this tax.
        """
        if (amount := self._get_raw_tax_amount_currency(batch, tax_data, base_untaxed, fix_rate=fix_rate)) is not None:
            return amount

        tax = tax_data['tax']
        if tax.amount_type == 'division':
            division_total_percentage = sum(
                tax_data['tax'].amount
                for tax_data in tax_data['_batch']['taxes_data']
                if tax_data['tax'].amount_type == 'division'
            ) / 100.0
            division_incl_base_multiplicator = 1.0 if division_total_percentage == 1.0 else 1 - division_total_percentage
            return tax.amount * base_untaxed / 100.0 / division_incl_base_multiplicator

        if tax.amount_type == 'percent':
            return tax.amount * base_untaxed / 100.0

    @api.model
    def _get_price_included_raw_tax_amount_currency(self, batch, tax_data, base_taxed, fix_rate=1.0):
        """ Compute the tax amount for a specific tax in the price-included context.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param batch:           The current batch that is evaluated (see '_batch_taxes_per_computation_base').
        :param tax_data:        The current tax_data inside the batch that is evaluated.
        :param base_taxed:      The computation base tax included (price_unit * quantity * (1 - discount))
                                plus or minus the taxes affecting the base of the current batch
                                on which we have to compute the tax amount.
        :param fix_rate:        For taxes that doesn't scale based on the 'base' passed as parameter, we have to multiply the
                                result by 'fix_rate' that might be different of 1.0 when the taxes engine is computed using the currency
                                of the company instead of the foreign one.
                                In others words, when computed in company currency, 'fix_rate' contains the rate between the foreign currency
                                and the national currency.
        :return:                The raw tax amount for this tax.
        """
        if (amount := self._get_raw_tax_amount_currency(batch, tax_data, base_taxed, fix_rate=fix_rate)) is not None:
            return amount

        tax = tax_data['tax']
        if tax.amount_type == 'division':
            return tax.amount * base_taxed / 100.0

        if tax.amount_type == 'percent':
            total_percentage = sum(
                tax_data['tax'].amount
                for tax_data in tax_data['_batch']['taxes_data']
                if tax_data['tax'].amount_type == 'percent'
            ) / 100.0
            percentage_incl_base_multiplicator = 1 / (1 + total_percentage) if total_percentage != -1 else 0.0
            return percentage_incl_base_multiplicator * tax.amount * base_taxed / 100.0

    @api.model
    def _get_batch_affect_base_tax_amount(self, batch, field_type, in_foreign_currency=True):
        """ Compute the tax amount affecting the computation base of the current batch.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param batch:               The current batch that is evaluated (see '_batch_taxes_per_computation_base').
        :param field_type:          Define the value to be taken into account to affect the base.

                                    Let's jump directly in an example. Suppose:
                                        t1 a fixed tax of 0.374 that affects the base of the subsequent taxes.
                                        t2 a percent tax of 21%.
                                        2 base lines b1 & b2 of 100.0 having both taxes.

                                    Let's say the computation of t1 is giving those results:
                                        <b1:t1:raw_tax_amount> = 0.374
                                        <b2:t1:raw_tax_amount> = 0.374
                                    After the rounding of the tax amounts and a global distribution on both lines:
                                        <b1:t1:tax_amount> = 0.38
                                        <b2:t1:tax_amount> = 0.37
                                    After the distribution of rounded amounts across the base_lines:
                                        <b1:t1:tax_amount_distr> = 0.375
                                        <b2:t1:tax_amount_distr> = 0.375

            * rounded:                  It means we want to account the tax amounts after rounding from the dependencies of the current
                                        batch. In our example, this method will return <b1:t1:tax_amount> for <b1:t2>.
            * rounded_distr:            It means we want to account the tax amounts distributed after rounding from the dependencies of the current
                                        batch. In our example, this method will return <b1:t1:tax_amount_distr> for <b1:t2>.
            * raw:                      It means we want to account the raw tax amounts from the dependencies of the current
                                        batch. In our example, this method will return <b1:t1:raw_tax_amount> for <b1:t2>.
        :param in_foreign_currency:     True if we want the amounts in foreign currency, False if we want the amounts expressed in company
                                        currency.
        :return:                        The tax amount affecting the computation base of the current batch.
        """
        if field_type == 'rounded':
            field = 'tax_amount_currency' if in_foreign_currency else 'tax_amount'
        elif field_type == 'rounded_distr':
            field = 'tax_amount_currency_distr' if in_foreign_currency else 'tax_amount_distr'
        else:  # elif field_type == 'raw':
            field = 'raw_tax_amount_currency' if in_foreign_currency else 'raw_tax_amount'
        return sum(
            sign * dep_tax_data[field].value()
            for sign, dep_batch in batch['dependencies']
            for dep_tax_data in dep_batch['taxes_data']
        )

    @api.model
    def _get_batch_tax_amount(self, batch, field_type='raw', in_foreign_currency=True):
        """ Compute the total tax amount for the current batch.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param batch:                   The current batch that is evaluated (see '_batch_taxes_per_computation_base').
        :param field_type:              'rounded', 'rounded_distr' or 'raw'. See '_get_batch_affect_base_tax_amount' for more details.
        :param in_foreign_currency:     True if we want the amounts in foreign currency, False if we want the amounts expressed in company
                                        currency.
        :return:                        The total tax amount for the current batch.
        """
        if field_type == 'rounded':
            field = 'tax_amount_currency' if in_foreign_currency else 'tax_amount'
        elif field_type == 'rounded_distr':
            field = 'tax_amount_currency_distr' if in_foreign_currency else 'tax_amount_distr'
        else:  # elif field_type == 'raw':
            field = 'raw_tax_amount_currency' if in_foreign_currency else 'raw_tax_amount'
        return sum(tax_data[field].value() for tax_data in batch['taxes_data'])

