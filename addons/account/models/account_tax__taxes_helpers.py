    @api.model
    def _split_base_line(self, base_line, company, target_factors, populate_function=None):
        """ Split a base lines into multiple ones. When computing taxes, the results should be
        exactly the same with a single base_line or after the split.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param base_line:           A base line.
        :param company:             The company owning the base line.
        :param target_factors:      A list of dictionary containing at least 'factor' being the weight
                                    defining how much delta will be allocated to this factor.
        :param populate_function:   An optional method to change the parameter of '_prepare_base_line_for_taxes_computation'
                                    when creating the new base lines from the one passed as parameter. This method takes
                                    the same parameter as '_prepare_base_line_for_taxes_computation'.
        :return:                    A list of base lines.
        """
        factors = self._normalize_target_factors(target_factors)['plus_factors']

        new_base_lines = []
        for _index, factor in factors:
            kwargs = {
                'price_unit': factor * base_line['price_unit'],
            }
            if populate_function:
                populate_function(base_line, factor, kwargs)
            new_base_line = self._prepare_base_line_for_taxes_computation(base_line, **kwargs)
            new_base_lines.append(new_base_line)
        self._add_tax_details(new_base_lines, company)

        self._ensure_base_lines_consistency(
            base_lines=[base_line],
            new_base_lines=new_base_lines,
            company=company,
        )

        self._fix_base_lines_tax_details_on_manual_tax_amounts(new_base_lines, company)
        return new_base_lines

    @api.model
    def _reduce_base_lines_total_amount(
        self,
        base_lines,
        company,
        amount_type,
        amount,
        computation_key=None,
    ):
        """

        :param base_lines:          A list of base lines generated using the '_prepare_base_line_for_taxes_computation' method.
        :param company:             The company of the base lines.
        :param amount_type:         'fixed' or 'percent' indicating the type of the down payment.
        :param amount:              The amount of the down payment in case of 'fixed' amount_type. Otherwise, a percentage [0-100].
        :param computation_key:     The key that will be used to split the base lines to round the tax amounts.
        :return:                    A new list of base lines having total amounts exactly matching the expected 'amount'/'amount_type'.
        """
        if not base_lines:
            return []

        currency = base_lines[0]['currency_id']

        # Turn the 'amount_type' / 'amount' into a percentage and the total amounts to be reached
        # from the base lines.
        total_excluded_amounts = self._get_base_lines_total_excluded_amounts(base_lines, company)
        tax_amounts = self._get_base_lines_tax_amounts(base_lines, company)
        total_amount_currency = (
            sum(amounts['total_excluded_currency'] for amounts in total_excluded_amounts.values())
            + sum(amounts['tax_amount_currency'] for amounts in tax_amounts.values())
        )

        sign = -1 if amount < 0.0 else 1
        signed_amount = sign * amount
        if amount_type == 'fixed':
            percentage = (signed_amount / total_amount_currency) if total_amount_currency else 0.0
        else:  # if amount_type == 'percent':
            percentage = signed_amount / 100.0

        # Compute exactly the expected amounts for the new lines.
        expected_tax_amounts = {
            grouping_key: {
                'tax_amount_currency': currency.round(amounts['tax_amount_currency'] * sign * percentage),
                'tax_amount': company.currency_id.round(amounts['tax_amount'] * sign * percentage),
                'base_amount_currency': currency.round(amounts['base_amount_currency'] * sign * percentage),
                'base_amount': company.currency_id.round(amounts['base_amount'] * sign * percentage),
            }
            for grouping_key, amounts in tax_amounts.items()
        }
        expected_total_excluded_amounts = {}
        for grouping_key, amounts in total_excluded_amounts.items():
            sub_base_lines = amounts['base_lines']
            currency = grouping_key['currency']
            sub_tax_amounts = self._get_base_lines_tax_amounts(sub_base_lines, company)
            sub_total_amount_currency = currency.round(
                amounts['total_excluded_currency']
                + sum(x['tax_amount_currency'] for x in sub_tax_amounts.values())
            )
            sub_total_amount = company.currency_id.round(
                amounts['total_excluded']
                + sum(x['tax_amount'] for x in sub_tax_amounts.values())
            )
            sub_expected_total_amount_currency = currency.round(sub_total_amount_currency * sign * percentage)
            sub_expected_total_amount = currency.round(sub_total_amount * sign * percentage)
            sub_expected_tax_amounts = {
                grouping_key: {
                    'tax_amount_currency': currency.round(amounts['tax_amount_currency'] * sign * percentage),
                    'tax_amount': company.currency_id.round(amounts['tax_amount'] * sign * percentage),
                    'base_amount_currency': currency.round(amounts['base_amount_currency'] * sign * percentage),
                    'base_amount': company.currency_id.round(amounts['base_amount'] * sign * percentage),
                }
                for grouping_key, amounts in sub_tax_amounts.items()
            }
            expected_total_excluded_amounts[grouping_key] = {
                'total_excluded_currency': (
                    sub_expected_total_amount_currency
                    - sum(x['tax_amount_currency'] for x in sub_expected_tax_amounts.values())
                ),
                'total_excluded': (
                    sub_expected_total_amount
                    - sum(x['tax_amount'] for x in sub_expected_tax_amounts.values())
                ),
            }

        # Create the new base_lines that should reach this total.
        new_base_lines = []
        for base_line in base_lines:
            new_base_lines.append(self._prepare_base_line_for_taxes_computation(
                base_line,
                price_unit=base_line['price_unit'] * sign * percentage,
                computation_key=computation_key,
            ))
        self._add_tax_details(new_base_lines, company)

        self._ensure_base_lines_total_excluded_consistency(
            base_lines=new_base_lines,
            company=company,
            expected_amounts_map=expected_total_excluded_amounts,
        )
        self._ensure_base_lines_tax_amounts_consistency(
            base_lines=new_base_lines,
            company=company,
            expected_amounts_map=expected_tax_amounts,
        )
        self._fix_base_lines_tax_details_on_manual_tax_amounts(new_base_lines, company)
        return new_base_lines

