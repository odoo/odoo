    @api.model
    def _init_taxes_engine_functions(self, global_context):
        def set_lazy(items, field, method, *args):
            def unpack():
                method(*args)

            for item in items:
                item[field] = Compute(unpack)

        def set_zero(items, field):
            for item in items:
                item[field] = Compute(None)
                item[field].set(0.0)

        default_functions = global_context['default_functions']
        base_lines = global_context['base_lines']
        taxes_data_per_grouping_key = global_context['taxes_data_per_grouping_key']
        base_lines_per_grouping_key = global_context['base_lines_per_grouping_key']
        for base_line in base_lines:
            for batch in base_line['tax_details']['_batches']:
                items = [tax_data for tax_data in batch['taxes_data']]
                args = [global_context, batch]
                for key, method in default_functions.items():
                    if key.startswith('base_line_batch_') and method != '/':
                        field = key[16:]
                        if method:
                            set_lazy(items, field, method, *args)
                        else:
                            set_zero(items, field)
        for base_lines_grouping_key, base_lines in base_lines_per_grouping_key.items():
            items = [base_line['tax_details'] for base_line in base_lines]
            args = [global_context, base_lines_grouping_key, base_lines]
            for key, method in default_functions.items():
                if key.startswith('base_lines_') and method != '/':
                    field = key[11:]
                    if method:
                        set_lazy(items, field, method, *args)
                    else:
                        set_zero(items, field)
        for taxes_data_grouping_key, taxes_data in taxes_data_per_grouping_key.items():
            items = [tax_data for tax_data in taxes_data]
            args = [global_context, taxes_data_grouping_key, taxes_data]
            for key, method in default_functions.items():
                if key.startswith('taxes_') and method != '/':
                    field = key[6:]
                    if method:
                        set_lazy(items, field, method, *args)
                    else:
                        set_zero(items, field)

    @api.model
    def _apply_tax_lines(self, global_context):
        base_lines = global_context['base_lines']
        tax_lines = global_context['tax_lines']
        if not tax_lines:
            return

        company = global_context['company']

        total_per_tax_line_key = defaultdict(lambda: {
            'tax_amount_currency': 0.0,
            'tax_amount': 0.0,
            'taxes_data': [],
        })
        matching_keys = set()
        for tax_line in tax_lines:
            grouping_key = self._get_tax_line_grouping_key(global_context, tax_line)
            for key in grouping_key:
                matching_keys.add(key)

            sign = tax_line['sign']
            values = total_per_tax_line_key[frozendict(grouping_key)]
            values['tax_amount_currency'] += sign * tax_line['amount_currency']
            values['tax_amount'] += sign * tax_line['balance']

        for base_line in base_lines:
            for tax_data in base_line['tax_details']['taxes_data']:
                tax_data_grouping_key = frozendict({
                    k: v
                    for k, v in tax_data['_grouping_key'].items()
                    if k in matching_keys
                })
                if base_line['special_type']:
                    total_per_tax_line_key[tax_data_grouping_key]['tax_amount_currency'] -= tax_data['tax_amount_currency'].value()
                    total_per_tax_line_key[tax_data_grouping_key]['tax_amount'] -= tax_data['tax_amount'].value()
                elif tax_data_grouping_key in total_per_tax_line_key:
                    total_per_tax_line_key[tax_data_grouping_key]['taxes_data'].append(tax_data)

        for key, values in total_per_tax_line_key.items():
            for suffix, currency in (('_currency', key['currency']), ('', company.currency_id)):
                amounts = [values[f'tax_amount{suffix}']]
                target_factors = []
                for tax_data in values['taxes_data']:
                    target_factors.append({'factor': tax_data['raw_tax_amount_currency'].value(), 'tax_data': tax_data})

                result_factors = sum_and_distribute_amounts_to(amounts, target_factors, rounding=currency.rounding)
                for factor in result_factors:
                    tax_data = factor['tax_data']
                    tax_data[f'tax_amount{suffix}'].set(factor['amount'])

    @api.model
    def _apply_manual_tax_amounts(self, global_context):
        base_lines = global_context['base_lines']
        company = global_context['company']
        for base_line in base_lines:
            manual_tax_amounts = base_line['manual_tax_amounts']
            tax_details = base_line['tax_details']
            rate = base_line['rate']
            for suffix, currency in (('_currency', base_line['currency_id']), ('', company.currency_id)):
                total_field = f'total_excluded{suffix}'
                delta_field = f'delta_{total_field}'
                manual_field = f'manual_{total_field}'
                if base_line[manual_field] is not None:
                    tax_details[total_field].set(base_line[manual_field])
                    tax_details[delta_field] = 0.0
                    if suffix == '_currency' and rate:
                        tax_details['total_excluded'].set(company.currency_id.round(tax_details[total_field].value() / rate))

                for tax_data in tax_details['taxes_data']:
                    tax = tax_data['tax']
                    reverse_charge_sign = -1 if tax_data['is_reverse_charge'] else 1
                    current_manual_tax_amounts = manual_tax_amounts and manual_tax_amounts.get(str(tax.id)) or {}
                    for prefix, factor in (('base', 1), ('tax', reverse_charge_sign)):
                        field = f'{prefix}_amount{suffix}'
                        if field in current_manual_tax_amounts:
                            tax_data[field].set(currency.round(factor * current_manual_tax_amounts[field]))
                            if suffix == '_currency' and rate:
                                tax_data[f'{prefix}_amount'].set(company.currency_id.round(tax_data[field].value() / rate))

