    @api.model
    def _dispatch_taxes_into_new_base_lines(self, base_lines, company, exclude_function):
        """ Extract taxes from base lines and turn them into sub-base lines.

        [!] Mirror of the same method in account_tax.js.
        PLZ KEEP BOTH METHODS CONSISTENT WITH EACH OTHERS.

        :param base_lines:          A list of base lines generated using the '_prepare_base_line_for_taxes_computation' method.
        :param company:             The company of the base lines.
        :param exclude_function:    A function taking a base line and a tax_data as parameter and returning
                                    a boolean indicating if the tax_data has to be exclude or not.
        :return:                    The new base lines with some extra data that have been removed.
                                    The newly created base lines will be under the 'removed_taxes_data_base_lines' key.
        """
        def partition_function(base_line, tax_data):
            return not exclude_function(base_line, tax_data)

        base_lines_partition_taxes = self._partition_base_lines_taxes(base_lines, partition_function)[0]

        new_base_lines_list = [[] for _base_line in base_lines]
        to_process = [
            (index, base_line, taxes_to_exclude)
            for index, (base_line, taxes_to_keep, taxes_to_exclude) in enumerate(base_lines_partition_taxes)
        ]
        while to_process:
            index, base_line, taxes_to_exclude = to_process[0]
            to_process = to_process[1:]

            tax_details = base_line['tax_details']
            taxes_data = tax_details['taxes_data']

            # Get the index of the next 'tax_data' to exclude.
            next_split_index = None
            for i, tax_data in enumerate(taxes_data):
                if tax_data['tax'] in taxes_to_exclude:
                    next_split_index = i
                    break

            if next_split_index is None:
                new_base_lines_list[index].append(dict(base_line))
                continue

            common_taxes_data = taxes_data[:next_split_index]
            tax_data_to_remove = taxes_data[next_split_index]
            remaining_taxes_data = taxes_data[next_split_index + 1:]

            common_taxes = self.env['account.tax']
            for tax_data in common_taxes_data:
                common_taxes += tax_data['tax']
            remaining_taxes = self.env['account.tax']
            for tax_data in remaining_taxes_data:
                remaining_taxes += tax_data['tax']

            total_excluded_first_base_line = self._prepare_base_line_for_taxes_computation(
                base_line,
                price_unit=self._infer_price_unit_from_new_base(
                    base=tax_details['raw_total_excluded_currency'],
                    quantity=base_line['quantity'],
                    discount=base_line['discount'],
                ),
                tax_ids=common_taxes + remaining_taxes,
                special_mode='total_excluded',
            )
            second_base_line_taxes = remaining_taxes.filtered(lambda tax: (
                tax._can_be_discounted()
                and tax in tax_data_to_remove['taxes']
            ))
            total_excluded_second_base_line = self._prepare_base_line_for_taxes_computation(
                base_line,
                price_unit=self._infer_price_unit_from_new_base(
                    base=tax_data_to_remove['raw_tax_amount_currency'],
                    quantity=base_line['quantity'],
                    discount=base_line['discount'],
                ),
                tax_ids=second_base_line_taxes,
                special_mode='total_excluded',
            )
            new_base_lines = [total_excluded_first_base_line, total_excluded_second_base_line]
            self._add_tax_details(new_base_lines, company)

            first_base_line = self._prepare_base_line_for_taxes_computation(
                total_excluded_first_base_line,
                price_unit=self._infer_price_unit_from_new_base(
                    base=(
                        total_excluded_first_base_line['tax_details']['raw_total_excluded_currency']
                        + sum(
                            tax_data['tax_amount_currency']
                            for tax_data in total_excluded_first_base_line['tax_details']['taxes_data']
                            if tax_data['original_price_include']
                        )
                    ),
                    quantity=base_line['quantity'],
                    discount=base_line['discount'],
                ),
                special_mode=base_line['special_mode'],
            )
            second_base_line = self._prepare_base_line_for_taxes_computation(
                total_excluded_second_base_line,
                price_unit=self._infer_price_unit_from_new_base(
                    base=(
                        total_excluded_second_base_line['tax_details']['raw_total_excluded_currency']
                        + sum(
                            tax_data['tax_amount_currency']
                            for tax_data in total_excluded_second_base_line['tax_details']['taxes_data']
                            if tax_data['original_price_include']
                        )
                    ),
                    quantity=base_line['quantity'],
                    discount=base_line['discount'],
                ),
                special_mode=base_line['special_mode'],
                _removed_tax_data=tax_data_to_remove,
            )

            new_base_lines = [first_base_line, second_base_line]
            self._add_tax_details(new_base_lines, company)

            # Ensure consistency between amounts.
            expected_total_excluded_amounts_map = self._get_base_lines_total_excluded_amounts([base_line], company)
            values = expected_total_excluded_amounts_map[frozendict(self._get_base_lines_total_excluded_amounts_grouping_key(base_line))]
            values['total_excluded_currency'] += tax_data_to_remove['tax_amount_currency']
            values['total_excluded'] += tax_data_to_remove['tax_amount']
            self._ensure_base_lines_total_excluded_consistency(
                base_lines=new_base_lines,
                company=company,
                expected_amounts_map=expected_total_excluded_amounts_map,
            )

            expected_tax_amounts_map = self._get_base_lines_tax_amounts([base_line], company)
            self._ensure_base_lines_tax_amounts_consistency(
                base_lines=new_base_lines,
                company=company,
                expected_amounts_map=expected_tax_amounts_map,
            )
            self._fix_base_lines_tax_details_on_manual_tax_amounts(
                base_lines=new_base_lines,
                company=company,
            )

            to_process = [
                (index, first_base_line, taxes_to_exclude),
                (index, second_base_line, taxes_to_exclude),
            ] + to_process

        final_base_lines = []
        for new_base_lines in new_base_lines_list:
            new_base_lines[0]['removed_taxes_data_base_lines'] = new_base_lines[1:]
            final_base_lines.append(new_base_lines[0])

        return final_base_lines

