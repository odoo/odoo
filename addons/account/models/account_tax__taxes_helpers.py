    @api.model
    def _batch_taxes_per_computation_base(self, base_line):
        """ Group taxes into distinct computation batches.

        Taxes requiring the same mathematical base and having the same type are batched together.
        This method is the key to know in which sequence the taxes will be evaluated and how they
        are affecting the others.

        Indian case:
        A base_line having 2 taxes: t1 <CGST 6%> + t2 <SGST 6%>, both a price included and affect the base
        of the others except t2 is not affected by the previous tax.
        It means both taxes are included in the price and need to be computed together.
        Suppose now t3 being a 3% price-excluded tax after.
        Since t1 & t2 affect the base of t3, 2 batches will be created: one for t1 & t2, one for t3.

        base_line:  <t1>    <t2>    <t3>
                    |__________|   |____|
                    batch 1        batch 2

        :param base_line:       A base line generated by '_prepare_base_line_for_taxes_computation'.
        :return:                A list of batches, each one being a dictionary containing:
            * amount_type:          The 'amount_type' of the contained taxes.
            * price_include:        If the batch is included in price or not.
            * include_base_amount:  If the batch affects the base of the subsequent batches.
            * is_base_affected:     If the batch has a base that is affected by the previous batches having 'include_base_amount' set to True.
            * taxes_data:           A list of tax_data belonging to the base_line passed as parameter that are part of the batch.
            * affect_base_taxes:    A recordset of account.tax that are the taxes having a base affected by this batch.
            * dependencies:         A list of <factor, dep_batch> defining which batches have to be computed before the current one.
                                    The factor defined if the tax amounts of the dependencies have to be added or subtracted from the
                                    initial computation base (price_unit * quantity * (1 - discount)) to be able to compute the current batch
                                    in the right order.
        """

        def get_tax_config(tax_data):
            tax = tax_data['tax']

            return {
                'amount_type': tax.amount_type,
                'price_include': tax_data['price_include'],
                'include_base_amount': tax.include_base_amount,
                'is_base_affected': tax.is_base_affected,
            }

        def add_dependency(batch, dep_batch, factor):
            batch['dependencies'].append((factor, dep_batch))

        def add_affect_base_taxes(batch, affect_batch):
            for tax_data in affect_batch['taxes_data']:
                batch['affect_base_taxes'] |= tax_data['tax']

        taxes_data = base_line['tax_details']['taxes_data']
        batches = []
        index = 0
        while index < len(taxes_data):
            tax_data = taxes_data[index]
            tax = tax_data['tax']
            index += 1

            batch = {'taxes_data': []}
            batch['taxes_data'].append(tax_data)
            batch.update(get_tax_config(tax_data))
            batch['dependencies'] = []
            batch['affect_base_taxes'] = self.env['account.tax']

            # Search for taxes that belong to the same batch.
            for sub_index, next_tax_data in enumerate(taxes_data[index:]):
                next_tax_data_config = get_tax_config(next_tax_data)

                if (
                    next_tax_data_config['price_include'] != batch['price_include']
                    or next_tax_data_config['amount_type'] != batch['amount_type']
                ):
                    break

                next_tax = next_tax_data['tax']
                if next_tax == tax:
                    batch['taxes_data'].append(next_tax_data)
                    index += 1
                    continue

                if (
                    (
                        batch['price_include']
                        and (
                            (not tax.include_base_amount and not next_tax.include_base_amount)
                            or not next_tax.is_base_affected
                        )
                    ) or (
                        not batch['price_include']
                        and tax.include_base_amount == next_tax.include_base_amount
                        and (
                            (
                                tax.include_base_amount
                                and next_tax.include_base_amount
                                and not next_tax.is_base_affected
                            )
                            or not tax.include_base_amount
                        )
                    )
                ):
                    batch['taxes_data'].append(next_tax_data)
                    index += 1
                    continue

                break

            for previous_batch in batches:
                if (
                    not batch['price_include']
                    and previous_batch['price_include']
                ):
                    if previous_batch['include_base_amount']:
                        if batch['is_base_affected']:
                            add_affect_base_taxes(previous_batch, batch)
                        else:
                            add_dependency(batch, previous_batch, -1)
                    elif batch['is_base_affected']:
                        add_dependency(batch, previous_batch, -1)
                elif (
                    not batch['price_include']
                    and not previous_batch['price_include']
                ):
                    if previous_batch['include_base_amount'] and batch['is_base_affected']:
                        add_dependency(batch, previous_batch, 1)
                        add_affect_base_taxes(previous_batch, batch)
                elif (
                    batch['price_include']
                    and previous_batch['price_include']
                ):
                    add_dependency(previous_batch, batch, -1)
                    add_affect_base_taxes(previous_batch, batch)

            batches.append(batch)

        if not batches:
            batches.append({
                'taxes_data': [],
                'price_include': False,
                'include_base_amount': False,
                'is_base_affected': True,
            })

        return batches

    def _round(self, amount, rounding_precision, rounding_method, currency=None):
        if rounding_precision is None:
            if currency:
                rounding_precision = currency.rounding
            else:
                return amount
        if rounding_method is None:
            rounding_method = 'HALF-UP'
        return float_round(amount, precision_rounding=rounding_precision, rounding_method=rounding_method)

    @api.model
    def _sum_and_distribute_amounts_globally(self, items, get_factor, set_value, get_amount=None, rounding=None, round_distr=True):
        amounts = []
        target_factors = []
        for item in items:
            factor = get_factor(item)
            target_factors.append({'factor': factor, 'item': item})
            if get_amount is None:
                amount = factor
            else:
                amount = get_amount(item)
            amounts.append(amount)

        result_factors = sum_and_distribute_amounts_to(amounts, target_factors, rounding=rounding, round_distr=round_distr)
        for factor in result_factors:
            item = factor['item']
            set_value(item, factor['amount'])

    @api.model
    def _distribute_amount_globally(self, items, amount, get_factor, set_value, rounding=None, round_distr=True):
        target_factors = []
        for item in items:
            factor = get_factor(item)
            target_factors.append({'factor': factor, 'item': item})

        result_factors = sum_and_distribute_amounts_to([amount], target_factors, rounding=rounding, round_distr=round_distr)
        for factor in result_factors:
            item = factor['item']
            set_value(item, factor['amount'])

