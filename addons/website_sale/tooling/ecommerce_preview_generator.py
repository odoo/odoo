def warn_unstamped_texts(soup, preview_texts, output_path):
    """Warn about a fake catalog text that survived stamping unmarked.

    ``stamp_texts`` marks every occurrence of a known text it finds, so
    whatever it left plain is a text the mapping never keyed to a picture --
    invisible here, but a style rendering the placeholder catalog forever once
    served, since the substitution has nothing to hook it on.
    """
    leftovers = {
        text
        for text_node in soup.find_all(string=True)
        if (text := text_node.strip()) in preview_texts
        and TEXT_KEY_ATTRIBUTE not in text_node.parent.attrs
    }
    if leftovers:
        print(
            f"  WARN: {output_path.name} left unstamped: {sorted(leftovers)}",
            file=sys.stderr,
        )


