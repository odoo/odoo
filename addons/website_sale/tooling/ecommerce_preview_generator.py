def get_filestore_dir(database):
    """Where the attachments of a database live: a copy needs them too."""
    add_odoo_to_path()
    from odoo.tools import config

    return Path(config.filestore(database))


def drop_database(database):
    # --force: a leftover connection would otherwise abort the whole run.
    subprocess.run(["dropdb", "--if-exists", "--force", database], check=True)
    shutil.rmtree(get_filestore_dir(database), ignore_errors=True)


def prepare_base_database():
    """Init the base database once: install ``website_sale``, seed the catalog.

    Every style later gets a Postgres template copy of this database, so the
    (slow) module install and the catalog seeding happen a single time for the
    whole run.

    Returns the product whose page is previewed: every copy holds the same
    records, so its id is the same for all the previews.
    """
    print(f"Preparing base database {BASE_DATABASE} (website_sale install, once).")
    drop_database(BASE_DATABASE)
    # --without-demo: the demo catalog would show up next to the fake one.
    server = start_odoo(BASE_DATABASE, "--init=website_sale", "--without-demo=True")
    session = requests.Session()
    try:
        wait_for_odoo(server)
        context = login(session, BASE_DATABASE).get("user_context", {})
        return seed_catalog(session, context)
    finally:
        session.close()
        stop_odoo(server)


def copy_database(target):
    """Clone the base database into ``target`` via a template copy.

    ``CREATE DATABASE ... TEMPLATE`` is a fast file-level copy and needs no open
    connection to the template -- the base Odoo process has already exited. The
    filestore holds the seeded product and category images, so it is copied too.
    """
    drop_database(target)
    subprocess.run(["createdb", "--template", BASE_DATABASE, target], check=True)
    filestore = get_filestore_dir(BASE_DATABASE)
    if filestore.is_dir():
        shutil.copytree(filestore, get_filestore_dir(target))


def start_odoo(database, *extra_args):
    command = [sys.executable, str(ODOO_BIN), *build_odoo_args(database, *extra_args)]
    return subprocess.Popen(command, cwd=ODOO_BIN.parent)


def wait_for_odoo(server):
    # Installing website_sale on an empty database takes a few minutes.
    deadline = time.time() + 900
    while time.time() < deadline:
        if server.poll() is not None:
            raise RuntimeError("Odoo stopped before it was ready.")
        try:
            response = requests.get(f"{BASE_URL}/web/login", timeout=5)
            if response.ok:
                return
        except requests.RequestException:
            pass
        time.sleep(1)
    raise RuntimeError("Odoo did not start in time.")


