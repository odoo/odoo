import logging

from datetime import timedelta

from odoo import api, fields, models
from odoo.exceptions import ValidationError

_logger = logging.getLogger(__name__)

# Maya statuses meaning the money reached the merchant. They are reversible by a refund or a void,
# which is a decision taken in Odoo afterwards and not something the QRPH code can still change.
# An authorization on the other hand only holds funds, so it is not a payment to register yet.
QRPH_PAID_STATUSES = ('PAYMENT_SUCCESS', 'CAPTURED')
# Maya statuses a payment never leaves: the code behind it is dead and a new one must be generated.
QRPH_FINAL_STATUSES = (
    'AUTH_FAILED',
    'CAPTURE_HOLD_EXPIRED',
    'PAYMENT_CANCELLED',
    'PAYMENT_EXPIRED',
    'PAYMENT_FAILED',
    'REFUNDED',
    'VOIDED',
)

# Maya expires a dynamic QRPH code one hour after minting it, and only ever takes one payment on
# it. We hand out the same code for well less than that, so that a payment screen left open is
# refreshed with a code that is still good rather than one Maya is about to refuse.
QRPH_REUSE_SECONDS = 900

# A code nobody paid within a day will not be paid anymore; the cron has long stopped looking at it.
QRPH_RETENTION_DAYS = 1


class L10n_PhQrphTransaction(models.Model):
    _name = 'l10n_ph.qrph.transaction'
    _description = "QRPH code generated by Maya"
    _order = 'create_date desc, id desc'

    # The paid record is referenced by name rather than by a Many2one because a point of sale order
    # is only stored once it is paid, so the code outlives the moment where the record exists.
    model = fields.Char(string="Model", required=True)
    model_id = fields.Char(string="Record", required=True, help="Id of an invoice, uuid of a point of sale order.")

    bank_id = fields.Many2one('res.partner.bank', string="Bank Account", required=True, ondelete='cascade')
    company_id = fields.Many2one(related='bank_id.company_id', store=True)
    currency_id = fields.Many2one('res.currency', string="Currency", required=True)
    amount = fields.Monetary(string="Amount", required=True)
    reference = fields.Char(string="Reference", help="Reference this payment was requested with on Maya.")

    maya_payment_id = fields.Char(string="Maya Payment", required=True, index='btree_not_null')
    qr_code_body = fields.Char(string="QR Code", required=True)
    maya_status = fields.Char(string="Maya Status", readonly=True)
    state = fields.Selection(
        selection=[
            ('pending', "Waiting for Payment"),
            ('paid', "Paid"),
            ('failed', "Failed"),
        ],
        string="Status",
        default='pending',
        required=True,
    )
    # Whether Maya has the money and whether Odoo recorded it are two different questions: a code
    # can sit paid for a while before anything settles it, and a settled one must never settle again.
    settled_date = fields.Datetime(
        string="Settled on",
        readonly=True,
        copy=False,
        help="When the payment of this code was recorded in Odoo.",
    )

    @api.constrains('model')
    def _check_model(self):
        supported_models = self._get_supported_models()
        for transaction in self:
            if transaction.model not in supported_models:
                raise ValidationError(self.env._("QRPH codes cannot be generated for %s.", transaction.model))

    def _get_supported_models(self):
        """ Return the models a QRPH code can be generated for. """
        return ['account.move']

    def _get_record(self):
        """ Return the record this code was generated to pay, empty if it is not stored yet. """
        self.ensure_one()
        if self.model == 'account.move':
            return self.env['account.move'].browse(int(self.model_id)).exists()
        return None

    @api.model
    def _get_latest_transaction(self, model, model_id):
        """ Return the most recent code generated for a record, if any. """
        if not model or not model_id:
            return self.browse()
        return self.search([('model', '=', model), ('model_id', '=', model_id)], limit=1)

    def _is_reusable(self, amount):
        """ Whether this code can be shown again instead of asking Maya for a new one.

        :param float amount: the amount the code is being asked for, which may have changed since
        :rtype: bool
        """
        self.ensure_one()
        return (
            self.state == 'pending'
            and self.currency_id.is_zero(self.amount - amount)
            and self.create_date > fields.Datetime.now() - timedelta(seconds=QRPH_REUSE_SECONDS)
        )

    def _update_state_from_maya(self):
        """ Ask Maya for the status of the pending codes in self, most recent first.

        Maya has no endpoint returning several payments at once, so this costs one request per code.
        A record is only ever paid once, so we stop as soon as we find the code that was paid.
        """
        for transaction in self.filtered(lambda transaction: transaction.state == 'pending'):
            # sudo: reading the Maya credentials of the bank account is reserved to system users,
            # while the status is checked by the cashier taking the payment or by a scheduled action.
            status = transaction.bank_id.sudo()._l10n_ph_qrph_fetch_payment_status(transaction.maya_payment_id)
            transaction.maya_status = status
            if status in QRPH_PAID_STATUSES:
                transaction.state = 'paid'
                break
            if status in QRPH_FINAL_STATUSES:
                transaction.state = 'failed'

    def _l10n_ph_qrph_settle(self):
        """ Record the payment of what this code was minted for.

        Maya repeats a notification it was given no answer to, and the record may also be settled
        by the cron or by someone asking for it, so paying twice has to amount to paying once: a
        code that already paid for something is done, whatever becomes of what it paid for.
        """
        self.ensure_one()
        if self.settled_date:
            return
        if self.model == 'account.move' and (invoice := self._get_record()):
            invoice._l10n_ph_qrph_update_payment_status()

    def _get_paid_transaction(self, amount=None):
        """ Return the code of self that Maya reports as paid and that is still to be recorded.

        :param float amount: what the caller is about to settle with the code, when it knows it.
            A code minted for less than that does not settle it: an order that grew after its code
            was handed out would otherwise be paid in full by the cheaper code it started as, as
            Maya has no way of taking a code back once it is out.
        :rtype: l10n_ph.qrph.transaction
        """
        self._update_state_from_maya()
        paid = self.filtered(
            lambda transaction: transaction.state == 'paid' and not transaction.settled_date
        )
        if amount is None:
            return paid[:1]

        covering = paid.filtered(
            lambda transaction: transaction.currency_id.compare_amounts(transaction.amount, amount) >= 0
        )
        if paid and not covering:
            # Real money reached Maya, only not enough of it to pay what it is being handed for.
            # Nobody but the merchant can settle that with the customer, so do not let it be silent.
            short = paid[:1]
            _logger.warning(
                "QRPH: Maya payment %s was paid %s, short of the %s owed on %s %s. Left unsettled.",
                short.maya_payment_id, short.amount, amount, short.model, short.model_id,
            )
        return covering[:1]

    @api.autovacuum
    def _gc_unpaid_transactions(self):
        self.search([
            ('state', '!=', 'paid'),
            ('create_date', '<', fields.Datetime.now() - timedelta(days=QRPH_RETENTION_DAYS)),
        ]).unlink()
