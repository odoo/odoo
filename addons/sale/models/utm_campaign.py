from odoo import api, fields, models
from odoo.libs.debug_log import DebugLog
from odoo.tools import SQL

_debug = DebugLog(__name__)


class UtmCampaign(models.Model):
    _inherit = "utm.campaign"
    _description = "UTM Campaign"

    sale_order_ids = fields.One2many(
        comodel_name="sale.order",
        inverse_name="campaign_id",
        string="Quotations",
    )
    quotation_count = fields.Integer(
        compute="_compute_quotation_count",
        compute_sudo=True,
        groups="sale.group_sale_salesman",
    )
    invoiced_amount = fields.Monetary(
        string="Revenues generated by the campaign",
        currency_field="currency_id",
        compute="_compute_invoiced_amount",
        compute_sudo=True,
        groups="sale.group_sale_salesman",
    )
    company_id = fields.Many2one(
        comodel_name="res.company",
        default=lambda self: self.env.company,
    )
    currency_id = fields.Many2one(
        comodel_name="res.currency",
        related="company_id.currency_id",
        string="Currency",
    )

    @api.depends("sale_order_ids")
    def _compute_quotation_count(self):
        quotation_data = self.env["sale.order"]._read_group(
            [("campaign_id", "in", self.ids)],
            ["campaign_id"],
            ["__count"],
        )
        data_map = {campaign.id: count for campaign, count in quotation_data}
        _debug.perf.count(
            "campaign_quotation_count", campaigns=len(self), rows=len(data_map)
        )
        for campaign in self:
            campaign.quotation_count = data_map.get(campaign.id, 0)

    def _compute_invoiced_amount(self):
        if self.ids:
            self.env["account.move.line"].flush_model(
                ["balance", "move_id", "account_id", "display_type"]
            )
            self.env["account.move"].flush_model(["state", "campaign_id", "move_type"])
            query_res = self.env.execute_query_dict(
                SQL(
                    """
                    SELECT move.campaign_id, -SUM(line.balance) as price_subtotal
                    FROM account_move_line line
                    INNER JOIN account_move move ON line.move_id = move.id
                    WHERE move.state not in ('draft', 'cancel')
                        AND move.campaign_id = ANY(%s)
                        AND move.move_type IN ('out_invoice', 'out_refund', 'in_invoice', 'in_refund', 'out_receipt', 'in_receipt')
                        AND line.account_id IS NOT NULL
                        AND line.display_type = 'product'
                    GROUP BY move.campaign_id
                    """,
                    list(self.ids),
                ),
            )
        else:
            query_res = []

        data_map = {
            datum["campaign_id"]: datum["price_subtotal"] for datum in query_res
        }
        _debug.perf.count(
            "campaign_invoiced_amount", campaigns=len(self), rows=len(data_map)
        )
        for campaign in self:
            campaign.invoiced_amount = data_map.get(campaign.id, 0)

    def action_redirect_to_quotations(self):
        action = self.env["ir.actions.actions"]._get_action_dict_by_xml_id(
            "sale.action_quotations_with_onboarding"
        )
        action["domain"] = [("campaign_id", "=", self.id)]
        action["context"] = {"default_campaign_id": self.id}
        return action

    def action_redirect_to_invoiced(self):
        action = self.env["ir.actions.actions"]._get_action_dict_by_xml_id(
            "account.action_move_journal_line"
        )
        invoices = self.env["account.move"].search([("campaign_id", "=", self.id)])
        _debug.logic("campaign_invoiced_action", campaign=self, invoices=invoices)
        action["context"] = {"create": False, "edit": False, "view_no_maturity": True}
        action["domain"] = [
            ("id", "in", invoices.ids),
            (
                "move_type",
                "in",
                (
                    "out_invoice",
                    "out_refund",
                    "in_invoice",
                    "in_refund",
                    "out_receipt",
                    "in_receipt",
                ),
            ),
            ("state", "not in", ["draft", "cancel"]),
        ]
        return action
