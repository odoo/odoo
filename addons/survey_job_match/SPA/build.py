# Rebuilt wholesale on every deploy: the page is build output, not something to
# edit in the builder. Mirrors the arch that website.new_page produces.
DEPLOY = r'''
import json
SECTION = json.loads(%(section)s)
URL = %(url)s
NAME = %(name)s
HIDE_HEADER = %(hide_header)s
HIDE_FOOTER = %(hide_footer)s

section = ('<section class="s_embed_code text-center pt16 pb16">'
           '<template class="s_embed_code_saved">' + SECTION + '</template>'
           '<div class="s_embed_code_embedded container o_not_editable">' + SECTION + '</div>'
           '</section>')

website = env['website'].search([], limit=1)
page = env['website.page'].search([('url', '=', URL)], limit=1)
if page:
    view = page.view_id
    view.arch = ('<t t-name="%%s">\n    <t t-call="website.layout">\n'
                 '        <div id="wrap" class="oe_structure oe_empty">%%s</div>\n'
                 '    </t>\n</t>' %% (view.key, section))
    action = 'updated'
else:
    res = env['website'].with_context(website_id=website.id).new_page(
        name=NAME, sections_arch=section, page_values={'is_published': True})
    page = env['website.page'].search([('url', '=', res['url'])], limit=1)
    action = 'created'

page.write({
    'is_published': True,
    'header_visible': not HIDE_HEADER,
    'footer_visible': not HIDE_FOOTER,
})
env.cr.commit()
print('DEPLOYED %%s %%s' %% (action, page.url))
'''


def deploy(database, payload, settings):
    script = DEPLOY % {
        'section': json.dumps(json.dumps(payload)),
        'url': json.dumps(settings['page_url']),
        'name': json.dumps(settings['page_name']),
        'hide_header': settings.get('hide_header', True),
        'hide_footer': settings.get('hide_footer', True),
    }
    cmd = [
        settings['python'], settings['odoo_bin'], 'shell',
        '-d', database,
        '--addons-path=%s' % settings['addons_path'],
        '--no-http', '--log-level=warn',
    ]
    print('Deploying to %s ...' % database)
    done = subprocess.run(cmd, input=script, capture_output=True, text=True)
    for line in done.stdout.splitlines():
        if line.startswith('DEPLOYED'):
            print('  %s' % line)
            return
    sys.exit('Deploy failed.\n%s\n%s' % (done.stdout[-2000:], done.stderr[-2000:]))


def page_url(settings):
    return settings['base_url'].rstrip('/') + settings['page_url']


def open_page(settings):
    """Show the freshly deployed page. Harmless when there is no browser."""
    url = page_url(settings)
    print('  opening %s' % url)
    try:
        if not webbrowser.open(url):
            print('  (no browser available -- open it yourself)')
    except Exception as err:
        print('  (could not open a browser: %s)' % err)


def main():
    with open(os.path.join(HERE, 'build.json'), encoding='utf-8') as fh:
        settings = json.load(fh)

    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--deploy', nargs='?', const=settings['database'],
                        metavar='DATABASE',
                        help='publish the built page, then open it. Defaults to '
                             'the database in build.json (%s).' % settings['database'])
    args = parser.parse_args()

    libs = read_dir('lib', '.js')
    screen_js = read_dir('screens', '.js')
    screen_html = read_dir('screens', '.html')
    chrome_html = read_dir('chrome', '.html')
    css = read_dir('styles', '.css')
    data = load_data()

    check_xml_safe(libs + screen_js, 'js')
    check_xml_safe(css, 'css')

    if not libs:
        sys.exit('Build failed: no lib/*.js found.')
    if not screen_html:
        sys.exit('Build failed: no screens/*.html found.')

    config = data.get('config', {})
    # Screens go in the card; chrome/ is the persistent UI around it (the fixed
    # toolbar and brand badge), which must sit outside the card's own clipping.
    markup = '<div id="jm_app">\n<div class="jm_card">\n%s\n</div>\n%s\n</div>' % (
        '\n'.join(content.strip() for _name, content in screen_html),
        '\n'.join(content.strip() for _name, content in chrome_html))
    stylesheet = '\n'.join(content.strip() for _name, content in css)

    # Every field the app writes needs un-blacklisting on the target database,
    # so the banner lists them all rather than assuming two.
    written = set(config.get('field_map', {}).values())
    written.add(config.get('note_field'))
    header = HEADER % {
        'model': config.get('model', '?'),
        'fields': ', '.join(sorted(f for f in written if f)) or '?',
    }

    os.makedirs(DIST, exist_ok=True)
    payload = compose(markup, stylesheet,
                      build_script(libs, screen_js, data, dev=False), header)
    check_comments(payload)
    with open(os.path.join(DIST, 'spa.html'), 'w', encoding='utf-8') as fh:
        fh.write(payload)

    preview = DEV_PAGE % {
        'title': config.get('title', 'SPA'),
        'markup': markup,
        'css': stylesheet,
        'script': build_script(libs, screen_js, data, dev=True),
    }
    with open(os.path.join(DIST, 'dev.html'), 'w', encoding='utf-8') as fh:
        fh.write(preview)

    sources = (len(libs) + len(screen_js) + len(screen_html)
               + len(chrome_html) + len(css) + len(data))
    print('Built dist/spa.html (%d bytes) and dist/dev.html from %d source files.'
          % (len(payload), sources))
    print('  screens: %s' % ', '.join(name for name, _c in screen_html))
    print('  chrome:  %s' % ', '.join(name for name, _c in chrome_html))
    print('  data:    %s' % ', '.join(sorted(data)))

    if args.deploy:
        deploy(args.deploy, payload, settings)
        open_page(settings)


if __name__ == '__main__':
    main()
