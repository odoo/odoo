import tempfile
from pathlib import Path
from textwrap import dedent

from odoo.tests.common import BaseCase, TransactionCase, tagged

from odoo.addons.web.tools import js_fields
from odoo.addons.web.tools.js_fields import (
    Addon,
    FieldsGenerator,
    JsClass,
    JsFieldsError,
    parse_directive,
    scan_js_classes,
)

MARKER = "// @generated by `odoo-bin js_fields` -- do not edit below the options"


def header(options):
    return f"{MARKER}\n//\n{dedent(options).strip()}\n"


class TestJsFieldsDirective(BaseCase):

    def test_options(self):
        directive = parse_directive(header("""
            // model: mail.message
            // addons: mail, crm
            // fields: author_id, body,
            //     parent_id
            //
            // some comment
            // export: messageFields
        """) + "\nexport const whatever = {};\n")
        self.assertEqual(directive.model, "mail.message")
        self.assertEqual(directive.addons, ("mail", "crm"))
        self.assertEqual(directive.fields, ("author_id", "body", "parent_id"))
        self.assertIsNone(directive.exclude)
        self.assertEqual(directive.export_name, "messageFields")
        self.assertTrue(directive.header.endswith("// export: messageFields"))

    def test_default_export_name(self):
        for model, name in [
            ("mail.message", "mailMessageFields"),
            ("res.partner", "resPartnerFields"),
            ("ir.mail_server", "irMailServerFields"),
            ("base", "baseFields"),
        ]:
            self.assertEqual(parse_directive(header(f"// model: {model}")).export_name, name)

    def test_invalid(self):
        for options, message in [
            ("// fields: name", "option 'model' is required"),
            ("// model: a.b\n// models: c.d", "unknown option 'models'"),
            ("// model: a.b\n// model: c.d", "option 'model' is given twice"),
            ("// model: a.b c.d", "option 'model' takes exactly one value"),
            ("// model: a.b\n// fields: x\n// exclude: y", "cannot be combined"),
            ("// model: a.b\n// export: not-a-name", "option 'export' is not a valid name"),
        ]:
            with self.subTest(options=options), self.assertRaisesRegex(JsFieldsError, message):
                parse_directive(header(options))
        with self.assertRaisesRegex(JsFieldsError, "the first line has to start with"):
            parse_directive("// model: a.b\n")


class TestJsFieldsClasses(BaseCase):

    def scan(self, content, path="partner_model.js", addon="mail"):
        addon = Addon(addon, Path("/addons") / addon)
        return scan_js_classes(addon, addon.path / "static" / "src" / path, dedent(content))

    def test_declaration(self):
        classes, warnings = self.scan("""
            import { Model } from "@web/next/store/model";
            import { resPartnerFields } from "./partner_fields.generated";

            /** @extends {Model<typeof resPartnerFields>} */
            export class Partner extends Model {
                static _name = "res.partner";
                static fields = resPartnerFields;
            }
        """, path="core/partner_model.js")
        self.assertEqual(classes, [
            JsClass("Partner", "res.partner", "mail", "@mail/core/partner_model", extension=False),
        ])
        self.assertFalse(warnings)

    def test_declaration_import(self):
        # an alias, and a relative import
        classes, _ = self.scan("""
            import { BUILD, Model as RecordModel } from "../store/model";

            export class Partner extends RecordModel {
                static _name = 'res.partner';
            }
        """, path="next/views/partner_model.js", addon="web")
        self.assertEqual([cls.name for cls in classes], ["Partner"])

    def test_not_a_store_model(self):
        classes, warnings = self.scan("""
            import { Record } from "@mail/model/export";
            import { Model } from "@web/model/model";

            export class Thread extends Record {
                static _name = "mail.thread";
            }
            export class Other extends Model {
                static _name = "other";
            }
            // export class Commented extends Model { static _inherit = "res.partner"; }
            /* static _inherit = "res.partner"; */
        """)
        self.assertFalse(classes)
        self.assertFalse(warnings)

    def test_extension(self):
        classes, _ = self.scan("""
            import { Partner } from "@web/core/partner_model";
            /** @import { Extension } from "@web/next/store/model" */

            export class MailPartner extends /** @type {Extension<typeof Partner, {}>} */ (
                /** @type {any} */ (Partner)
            ) {
                static _inherit = "res.partner";
                static fields = {};
            }
            export class Other extends Whatever {
                static _name = "other";
                static _inherit = "other";
            }
        """)
        self.assertEqual(classes, [
            JsClass("MailPartner", "res.partner", "mail", "@mail/partner_model", extension=True),
            JsClass("Other", "other", "mail", "@mail/partner_model", extension=True),
        ])

    def test_not_exported(self):
        classes, warnings = self.scan("""
            class MailPartner extends Partner {
                static _inherit = "res.partner";
            }
        """)
        self.assertFalse(classes)
        self.assertEqual(len(warnings), 1)
        self.assertIn("class MailPartner of model 'res.partner' is ignored", warnings[0])


class TestJsFieldsGenerate(TransactionCase):
    """ The addons are fake ones, in a temporary directory: the JS classes and the generated
    files are looked for in there. They are named after installed addons, as the fields come
    from the database.
    """

    def setUp(self):
        super().setUp()
        self.root = Path(self.enterContext(tempfile.TemporaryDirectory())).resolve()
        self.addons = {
            addon.name: addon for addon in [
                Addon("base", self.root / "base"),
                Addon("web", self.root / "web", ("base",)),
                Addon("not_installed", self.root / "not_installed", ("web",)),
            ]
        }
        self.write("base", "partner_model.js", """
            import { Model } from "@web/next/store/model";

            export class Partner extends Model {
                static _name = "res.partner";
            }
        """)

    def write(self, addon, name, content):
        path = self.addons[addon].path / "static" / "src" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(dedent(content).lstrip(), encoding="utf-8")
        return path

    def write_generated(self, addon, options, name="fields.generated.js"):
        return self.write(addon, name, header(options))

    def generate(self, addon, options):
        path = self.write_generated(addon, options)
        return FieldsGenerator(self.env, self.addons).generate(path)

    def assertGenerateError(self, addon, options, message):
        with self.assertRaisesRegex(JsFieldsError, message):
            self.generate(addon, options)

    def test_fields(self):
        options = """
            // model: res.partner
            // fields: name, parent_id, child_ids, active, color, type, create_date
        """
        content, notes = self.generate("base", options)
        self.assertEqual(content, header(options) + dedent("""
            import { fields } from "@web/next/store/fields";
            /** @import { Many2one, One2many } from "@web/next/store/fields" */
            /** @import { Partner } from "@base/partner_model" */

            export const resPartnerFields = {
                active: fields.Boolean(),
                child_ids: /** @type {One2many<Partner>} */ (
                    fields.One2many("res.partner", { inverse: "parent_id" })
                ),
                color: fields.Integer(),
                create_date: fields.Datetime(),
                name: fields.Char(),
                parent_id: /** @type {Many2one<Partner>} */ (fields.Many2one("res.partner")),
                type: fields.Selection(),
            };
        """))
        self.assertFalse(notes)

    def test_no_field(self):
        options = """
            // model: res.partner
            // fields:
            // export: nothing
        """
        content, _ = self.generate("base", options)
        self.assertEqual(content, header(options) + dedent("""
            import { fields } from "@web/next/store/fields";

            export const nothing = {};
        """))

    def test_all_fields(self):
        content, notes = self.generate("base", """
            // model: res.partner
            // exclude: name, parent_id
        """)
        self.assertIn("    child_ids: /** @type {One2many<Partner>} */ (", content)
        self.assertIn("    display_name: fields.Char(),", content)
        self.assertIn("    email: fields.Char(),", content)
        for name in ("id", "name", "parent_id", "create_uid", "write_date", "image_1920", "user_id"):
            self.assertNotIn(f"    {name}:", content)
        self.assertIn("field 'image_1920' is left out: type 'binary' has no JS declaration", notes)
        self.assertIn(
            "field 'user_id' is left out: model 'res.users' has no JS class 'base' can rely on",
            notes)
        self.assertFalse([note for note in notes if "'create_uid'" in note])
        # sorted by name
        names = [line.split(":")[0] for line in content.splitlines() if line.startswith("    ") and ":" in line]
        names = [name.strip() for name in names if not name.startswith("     ")]
        self.assertEqual(names, sorted(names))

    def test_inherited_field(self):
        # res.users inherits its name from res.partner
        content, _ = self.generate("base", "// model: res.users\n// fields: login, name")
        self.assertIn("    name: fields.Char(),", content)

    def test_addons(self):
        # all the fields of base.document.layout are introduced by web
        model = "// model: base.document.layout"
        content, _ = self.generate("web", model)
        self.assertIn("    display_name: fields.Char(),", content)
        self.assertIn("    primary_color: fields.Char(),", content)

        content, _ = self.generate("web", f"{model}\n// addons: web")
        self.assertNotIn("display_name", content)
        self.assertIn("    primary_color: fields.Char(),", content)

        content, _ = self.generate("web", f"{model}\n// addons: base")
        self.assertIn("    display_name: fields.Char(),", content)
        self.assertNotIn("primary_color", content)

        # what base cannot rely on
        content, _ = self.generate("base", model)
        self.assertNotIn("primary_color", content)
        self.assertGenerateError(
            "base", f"{model}\n// fields: primary_color",
            "field 'primary_color' comes from addon\\(s\\) web, not from: base")
        self.assertGenerateError(
            "web", f"{model}\n// addons: base\n// fields: primary_color",
            "field 'primary_color' comes from addon\\(s\\) web, not from: base")
        self.assertGenerateError(
            "base", f"{model}\n// exclude: primary_color",
            "field 'primary_color' comes from addon\\(s\\) web, not from: base")
        self.assertGenerateError(
            "base", f"{model}\n// addons: web",
            "addon 'web' is not 'base' or one of its dependencies")

    def test_comodel_classes(self):
        self.write("web", "web_partner_model.js", """
            import { Partner } from "@base/partner_model";

            export class WebPartner extends Partner {
                static _inherit = "res.partner";
            }
        """)
        options = "// model: res.partner\n// fields: parent_id"
        content, _ = self.generate("base", options)
        self.assertIn('/** @import { Partner } from "@base/partner_model" */', content)
        self.assertIn("    parent_id: /** @type {Many2one<Partner>} */ (", content)

        content, _ = self.generate("web", options)
        self.assertIn('/** @import { WebPartner } from "@web/web_partner_model" */', content)
        self.assertIn("    parent_id: /** @type {Many2one<WebPartner>} */ (", content)
        self.assertNotIn("@base/partner_model", content)

    def test_most_extended_classes(self):
        addons = {
            name: Addon(name, self.root / name, depends)
            for name, depends in [
                ("a", ()), ("b", ("a",)), ("c", ("a",)), ("d", ("b", "c")), ("e", ("d",)), ("f", ()),
            ]
        }
        generator = FieldsGenerator(self.env, addons)
        generator.classes = {
            "some.model": [
                JsClass("A", "some.model", "a", "@a/model", extension=False),
                JsClass("A2", "some.model", "a", "@a/extension", extension=True),
                JsClass("B", "some.model", "b", "@b/model", extension=True),
                JsClass("C", "some.model", "c", "@c/model", extension=True),
            ],
        }
        for addon, expected in [
            ("a", ["A2"]), ("b", ["B"]), ("c", ["C"]), ("d", ["B", "C"]), ("e", ["B", "C"]), ("f", []),
        ]:
            classes = generator.get_classes("some.model", addon)
            self.assertEqual([cls.name for cls in classes], expected, f"from addon {addon}")
        self.assertFalse(generator.get_classes("other.model", "e"))

    def test_invalid(self):
        for addon, options, message in [
            ("base", "// model: not.a.model", "unknown model 'not.a.model'"),
            ("base", "// model: res.partner\n// fields: nope", "unknown field 'nope' on model 'res.partner'"),
            ("base", "// model: res.partner\n// exclude: nope", "unknown field 'nope' on model 'res.partner'"),
            ("base", "// model: res.partner\n// fields: id", "field 'id' cannot be listed"),
            ("base", "// model: res.partner\n// fields: image_1920",
             "field 'image_1920' cannot be generated: type 'binary' has no JS declaration"),
            ("base", "// model: res.partner\n// fields: user_id",
             "field 'user_id' cannot be generated: model 'res.users' has no JS class"),
            ("not_installed", "// model: res.partner",
             "addon 'not_installed' is not installed in the database"),
        ]:
            with self.subTest(options=options):
                self.assertGenerateError(addon, options, message)

        path = self.write("base", "partner_fields.js", header("// model: res.partner"))
        with self.assertRaisesRegex(JsFieldsError, r"a generated file has to be named \*.generated.js"):
            FieldsGenerator(self.env, self.addons).generate(path)

        path = self.root / "elsewhere.generated.js"
        path.write_text(header("// model: res.partner"), encoding="utf-8")
        with self.assertRaisesRegex(JsFieldsError, "not in an addon of the addons path"):
            FieldsGenerator(self.env, self.addons).generate(path)

    def test_run(self):
        path = self.write_generated("base", "// model: res.partner\n// fields: name")
        invalid = self.write_generated("web", "// model: res.partner\n// fields: nope")
        # not a generated file of this tool
        other = self.write("web", "other.generated.js", "export const other = {};\n")
        generator = FieldsGenerator(self.env, self.addons)
        todo = path.read_text()

        def statuses(**kwargs):
            return {result.path: result.status for result in js_fields.run(generator, **kwargs)}

        self.assertEqual(statuses(check=True), {path: 'outdated', invalid: 'error'})
        self.assertEqual(path.read_text(), todo)

        self.assertEqual(statuses(), {path: 'updated', invalid: 'error'})
        done = path.read_text()
        self.assertIn("    name: fields.Char(),", done)
        self.assertEqual(other.read_text(), "export const other = {};\n")
        self.assertEqual(invalid.read_text(), header("// model: res.partner\n// fields: nope"))

        self.assertEqual(statuses(check=True), {path: 'unchanged', invalid: 'error'})
        self.assertEqual(statuses(roots=[path]), {path: 'unchanged'})

        # a manual edit is overwritten
        path.write_text(done.replace("fields.Char()", "fields.Text()"), encoding="utf-8")
        self.assertEqual(statuses(roots=[path.parent], check=True), {path: 'outdated'})
        self.assertEqual(statuses(roots=[path.parent]), {path: 'updated'})
        self.assertEqual(path.read_text(), done)

        results = js_fields.run(generator, roots=[other])
        self.assertEqual([result.status for result in results], ['error'])

        # a file with the header, but not named as a generated file
        misnamed = self.write("base", "misnamed.js", header("// model: res.partner"))
        self.assertEqual(statuses(roots=[misnamed]), {misnamed: 'error'})
        self.assertNotIn(misnamed, statuses())


@tagged('post_install', '-at_install')
class TestJsFieldsUpToDate(TransactionCase):

    def test_generated_files(self):
        """ The generated files of the installed addons are what `odoo-bin js_fields` writes. """
        generator = FieldsGenerator(self.env, js_fields.get_addons())
        roots = [
            root
            for addon in generator.addons.values()
            if addon.name in generator.installed and (root := addon.path / "static" / "src").is_dir()
        ]
        problems = [
            f"{result.status}: {result.path}" + "".join(f"\n    {message}" for message in result.messages)
            for result in js_fields.run(generator, roots, check=True)
            if result.status in ('outdated', 'error')
        ]
        self.assertFalse(problems, (
            "Some generated files are not up to date. Run `odoo-bin js_fields -d <database>` and "
            "commit the result.\n" + "\n".join(problems)
        ))
