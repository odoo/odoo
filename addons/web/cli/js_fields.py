import logging
import sys
from pathlib import Path

from odoo import api
from odoo.cli import Command
from odoo.modules.registry import Registry
from odoo.tools import config

_logger = logging.getLogger(__name__)


class JsFields(Command):
    """Generate the field declarations of JS store models from the Python models"""
    name = 'js_fields'
    epilog = """
        A generated file has to be named `*.generated.js`. It starts with a header that
        tells what to generate. To create one, write its header:

            // @generated by `odoo-bin js_fields` -- do not edit below the options
            //
            // model: mail.message
            // fields: author_id, body, parent_id

        The options are described in addons/web/tools/js_fields.py.

        The fields are read from the database: the addon of a generated file has
        to be installed in it.
    """

    def __init__(self):
        super().__init__()
        self.parser.add_argument(
            '-c', '--config', dest='config',
            help="use a specific configuration file")
        self.parser.add_argument(
            '-d', '--database', dest='db_name', default=None,
            help="database to read the models from")
        self.parser.add_argument(
            '--check', action='store_true',
            help="do not write anything: fail if a generated file is not up to date")
        self.parser.add_argument(
            'paths', nargs='*', metavar='PATH', type=Path,
            help="generated files, or directories to look for them in "
                 "(default: all the addons of the addons path)")

    def run(self, cmdargs):
        parsed_args = self.parser.parse_args(args=cmdargs)
        config_args = ['--no-http']
        if parsed_args.config:
            config_args += ['-c', parsed_args.config]
        if parsed_args.db_name:
            config_args += ['-d', parsed_args.db_name]
        config.parse_config(config_args, setup_logging=True)

        db_names = config['db_name']
        if not db_names or len(db_names) > 1:
            self.parser.error("Please provide a single database")
        for path in parsed_args.paths:
            if not path.exists():
                self.parser.error(f"No such file or directory: {path}")

        with Registry(db_names[0]).cursor() as cr:
            # imported late: the addons path is not known before the config is parsed
            from odoo.addons.web.tools import js_fields  # noqa: PLC0415

            env = api.Environment(cr, api.SUPERUSER_ID, {})
            generator = js_fields.FieldsGenerator(env, js_fields.get_addons())
            for warning in generator.warnings:
                _logger.warning("%s", warning)
            results = js_fields.run(generator, parsed_args.paths or None, check=parsed_args.check)

        failed = False
        for result in results:
            level = logging.INFO
            if result.status == 'error' or (parsed_args.check and result.status == 'outdated'):
                level = logging.ERROR
                failed = True
            _logger.log(level, "%s: %s", result.status, result.path)
            for message in result.messages:
                # the messages of an error are its reason, the other ones are only notes
                _logger.log(level if result.status == 'error' else logging.INFO, "    %s", message)
        if not results:
            _logger.info("No generated file found")
        sys.exit(1 if failed else 0)
