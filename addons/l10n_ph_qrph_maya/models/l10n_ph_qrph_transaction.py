import logging
from datetime import timedelta

from odoo import api, fields, models
from odoo.exceptions import ValidationError
from odoo.tools import format_amount

_logger = logging.getLogger(__name__)

# Maya statuses meaning the money reached the merchant. They are reversible by a refund or a void,
# which is a decision taken in Odoo afterwards and not something the QRPH transaction can still change.
# An authorization on the other hand only holds funds, so it is not a payment to register yet.
PAID_STATUSES = {'PAYMENT_SUCCESS', 'CAPTURED'}
# Maya statuses a payment never leaves: the transaction behind it is dead and a new one must be generated.
FINAL_STATUSES = {
    'AUTH_FAILED',
    'CAPTURE_HOLD_EXPIRED',
    'PAYMENT_CANCELLED',
    'PAYMENT_EXPIRED',
    'PAYMENT_FAILED',
    'REFUNDED',
    'VOIDED',
}

# Maya expires a dynamic QRPH code one hour after minting it, and only ever takes one payment on
# it. We hand out the same transaction for well less than that, so that a payment screen left open is
# refreshed with a transaction that is still good rather than one Maya is about to refuse.
REUSE_SECONDS = 900

# A transaction nobody paid within a day will not be paid anymore; the cron has long stopped looking at it.
RETENTION_DAYS = 1


class L10n_PhQrphTransaction(models.Model):
    _name = 'l10n_ph.qrph.transaction'
    _description = "QRPH transaction generated by Maya"
    _order = 'create_date desc, id desc'

    res_model = fields.Char(string="Model", required=True, readonly=True)
    res_id = fields.Many2oneReference(
        string="Record",
        model_field='res_model',
        index='btree_not_null',
        readonly=True,
        help="The record this transaction pays, empty as long as it is not stored yet.",
    )

    bank_id = fields.Many2one('res.partner.bank', string="Bank Account", required=True, ondelete='restrict')
    company_id = fields.Many2one(
        comodel_name='res.company',
        string="Company",
        required=True,
        readonly=True,
        index=True,
        default=lambda self: self.env.company,
    )
    currency_id = fields.Many2one('res.currency', string="Currency", required=True)
    amount = fields.Monetary(string="Amount", required=True)
    reference = fields.Char(string="Reference", help="Reference this payment was requested with on Maya.")

    maya_payment_id = fields.Char(string="Maya Payment", required=True, index='btree_not_null')
    qr_code_body = fields.Char(string="QR Code", required=True)
    maya_status = fields.Char(string="Maya Status", readonly=True)
    state = fields.Selection(
        selection=[
            ('pending', "Waiting for Payment"),
            ('paid', "Paid"),
            ('failed', "Failed"),
        ],
        string="Status",
        default='pending',
        required=True,
    )
    # Whether Maya has the money and whether Odoo recorded it are two different questions: a transaction
    # can sit paid for a while before anything settles it, and a settled one must never settle again.
    settled_date = fields.Datetime(
        string="Settled on",
        readonly=True,
        copy=False,
        help="When the payment of this transaction was recorded in Odoo.",
    )
    short_payment_notified = fields.Boolean(
        string="Short Payment Notified",
        readonly=True,
        copy=False,
        help="Whether the merchant was told this transaction was paid for less than what it was asked to settle.",
    )

    @api.constrains('res_model')
    def _check_model(self):
        supported_models = self._get_supported_models()
        for transaction in self:
            if transaction.res_model not in supported_models:
                raise ValidationError(self.env._("QRPH transactions cannot be generated for %s.", transaction.res_model))

    def _get_supported_models(self):
        """ Return the models a QRPH transaction can be generated for. """
        return ['account.move']

    def _get_record(self):
        """ Return the record this transaction was generated to pay, empty if it is not stored yet. """
        self.ensure_one()
        if not self.res_id:
            return self.env[self.res_model].browse()
        return self.env[self.res_model].browse(self.res_id).exists()

    @api.model
    def _get_record_vals(self, res_model, res_id, res_uuid=None):
        """ Return the values tying a new transaction to the record it is minted for.

        :param str res_model: the model of the record being paid
        :param str res_id: the identifier of the record being paid, as the caller knows it
        :param str res_uuid: the unique identifier of the record being paid, for a record that is
            not stored yet and has no identifier to give
        :rtype: dict
        """
        return {'res_model': res_model, 'res_id': int(res_id)}

    @api.model
    def _get_latest_transaction(self, model, model_id, company_id, model_uuid=None):
        """ Return the most recent transaction generated for a record of a company, if any.

        :param str model_uuid: the unique identifier of the record, for a record that is not stored yet
        """
        if not model or not model_id:
            return self.browse()
        return self.search([
            ('res_model', '=', model),
            ('res_id', '=', int(model_id)),
            ('company_id', '=', company_id),
        ], limit=1)

    def _is_reusable(self, bank, amount):
        """ Whether this transaction can be shown again instead of asking Maya for a new one.

        :param bank: the <res.partner.bank> the code is being asked for, which may have changed since:
            a code pays the account it was minted for
        :param float amount: the amount the transaction is being asked for, which may have changed since
        :rtype: bool
        """
        self.ensure_one()
        return (
            self.state == 'pending'
            and self.bank_id == bank
            and self.currency_id.compare_amounts(self.amount, amount) == 0
            and self.create_date > fields.Datetime.now() - timedelta(seconds=REUSE_SECONDS)
        )

    def _update_state_from_maya(self):
        """ Ask Maya for the status of the pending transactions in self, most recent first.

        Maya has no endpoint returning several payments at once, so this costs one request per transaction.
        A record is only ever paid once, so we stop as soon as we find the transaction that was paid.
        """
        for transaction in self:
            if transaction.state != 'pending':
                continue
            # sudo: reading the Maya credentials of the bank account is reserved to system users,
            # while the status is checked by the cashier taking the payment or by a scheduled action.
            # Only what Maya answers may change the state, so the checking user cannot write it.
            transaction = transaction.sudo()
            status = transaction.bank_id._l10n_ph_qrph_fetch_payment_status(transaction.maya_payment_id)
            transaction.maya_status = status
            if status in PAID_STATUSES:
                transaction.state = 'paid'
            elif status in FINAL_STATUSES:
                transaction.state = 'failed'

    def _get_paid_transaction(self, amount):
        """ Return the transaction of self that Maya reports as paid and that is still to be recorded.

        :param float amount: what the caller is about to settle with the transaction.
            A transaction minted for less than that does not settle it: an order that grew after its
            transaction was handed out would otherwise be paid in full by the cheaper transaction it
            started as, as Maya has no way of taking a transaction back once it is out.
        :rtype: l10n_ph.qrph.transaction
        """
        self._update_state_from_maya()
        paid = self.filtered(
            lambda transaction: transaction.state == 'paid' and not transaction.settled_date,
        )
        covering = paid.filtered(
            lambda transaction: transaction.currency_id.compare_amounts(transaction.amount, amount) >= 0,
        )
        if paid and not covering:
            # Real money reached Maya, only not enough of it to pay what it is being handed for.
            # Nobody but the merchant can settle that with the customer, so do not let it be silent.
            paid[:1]._notify_short_payment(amount)
        return covering[:1]

    def _notify_short_payment(self, amount):
        """ Tell the merchant this transaction was paid for less than what it was asked to settle, once.

        The note goes on the record being paid when it is stored, and in the log otherwise, as is
        the case for an order a cashier is still keying in at the point of sale.

        :param float amount: what the transaction was asked to settle
        """
        self.ensure_one()
        if self.short_payment_notified:
            return
        if record := self._get_record():
            # sudo: the one asking Maya, e.g. a kiosk customer, may not write on the record.
            record.sudo()._message_log(body=self.env._(
                "QRPH payment %(payment)s was paid %(paid)s, short of the %(owed)s owed. "
                "It was left unsettled: the difference has to be settled with the customer.",
                payment=self._get_html_link(title=self.maya_payment_id),
                paid=format_amount(self.env, self.amount, self.currency_id),
                owed=format_amount(self.env, amount, self.currency_id),
            ))
        else:
            _logger.warning(
                "QRPH: Maya payment %s was paid %s, short of the %s owed on %s %s. Left unsettled.",
                self.maya_payment_id, self.amount, amount, self.res_model, self.res_id,
            )
        # sudo: the merchant is told once, whoever asked Maya, and the flag is not theirs to write.
        self.sudo().short_payment_notified = True

    @api.autovacuum
    def _gc_unpaid_transactions(self):
        self.search([
            ('state', '!=', 'paid'),
            ('create_date', '<', fields.Datetime.now() - timedelta(days=RETENTION_DAYS)),
        ]).unlink()
