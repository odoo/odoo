# pointers to an equivalent date in both AD and BS
AD_SCALE = date(1943, 4, 14)
BS_SCALE = (2000, 1, 1)


def convert_ad_to_bs(date_in_ad):
    """
    Convert an AD date to a BS date.
    """
    if isinstance(date_in_ad, datetime):
        date_in_ad = date_in_ad.date()
    if not isinstance(date_in_ad, date):
        raise TypeError(f"Expected a date, got {date_in_ad}")

    diff_days = (date_in_ad - AD_SCALE).days
    if diff_days < 0:
        raise ValueError(f"{date_in_ad} is before the first supported date {AD_SCALE}")

    for year, months in BS_YEAR_TO_MONTHS.items():
        months_sum = sum(months)
        if diff_days >= months_sum:
            diff_days -= months_sum
            continue
        for month, days_in_month in enumerate(months, start=1):
            if diff_days < days_in_month:
                return year, month, diff_days + 1
            diff_days -= days_in_month

    raise ValueError(f"{date_in_ad} is after the last supported BS year {max(BS_YEAR_TO_MONTHS)}")
