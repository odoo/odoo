import odoo.tests

from odoo.addons.pos_self_order.tests.self_order_common_test import SelfOrderCommonTest


@odoo.tests.tagged("post_install", "-at_install")
class TestSelfOrderReceipt(SelfOrderCommonTest):
    def _open_self_ordering(self, **config_values):
        self.pos_config.write({
            'self_ordering_mode': 'mobile',
            'self_ordering_pay_after': 'each',
            **config_values,
        })
        self.pos_config.with_user(self.pos_user).open_ui()
        self.pos_config.current_session_id.set_opening_control(0, "")

    def _create_self_order(self, *, preset=None, table=None, **order_values):
        """Create an order like the mobile controller, without sending it to preparation."""
        order = self._create_order_data(
            [{'product': self.cola, 'qty': 1, 'price_unit': self.cola.lst_price}],
            preset=preset,
            table=table,
            device_type='mobile',
            **order_values,
        )['order']
        safe_data = self.env['pos.order']._check_pos_order(self.pos_config, order, 'mobile', table)
        result = self.env['pos.order'].sudo().sync_from_ui([safe_data])
        return self.env['pos.order'].browse(result['pos.order'][0]['id'])

    def _prep_ticket_extra_data(self, order):
        changes = order._generate_preparation_change_for_categories(
            set(self.env['pos.category'].search([]).ids)
        )
        receipts = order._generate_preparation_receipt_data(changes)
        self.assertTrue(receipts, "the order has a new line, it must produce a ticket")
        return receipts[0]['extra_data']

    def test_prep_ticket_drops_the_generated_table_label(self):
        """The scanned table gets its own line, the order label must not repeat it."""
        self._open_self_ordering(self_ordering_service_mode='table')
        order = self._create_self_order(preset=self.in_preset, table=self.pos_table_1)

        # generated by _get_self_order_floating_name, the customer never typed it
        self.assertEqual(order.floating_order_name, f"Self-Order T {self.pos_table_1.table_number}")

        extra_data = self._prep_ticket_extra_data(order)
        self.assertFalse(extra_data['order_label'])
        self.assertEqual(extra_data['table_name'], self.pos_table_1.table_number)
        self.assertEqual(extra_data['floor_name'], self.pos_main_floor.name)

    def test_prep_ticket_keeps_the_customer_name(self):
        """A preset asking for a name stores it in floating_order_name: that one is printed."""
        self._open_self_ordering(self_ordering_service_mode='table')
        order = self._create_self_order(
            preset=self.out_preset,
            table=self.pos_table_1,
            floating_order_name='My customer',
        )
        self.assertEqual(order.preset_id.identification, 'name')

        extra_data = self._prep_ticket_extra_data(order)
        self.assertEqual(extra_data['order_label'], 'My customer')
        self.assertEqual(extra_data['table_name'], self.pos_table_1.table_number)

