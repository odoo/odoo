from odoo import fields, models
from odoo.libs.debug_log import DebugLog
from odoo.tools import float_is_zero

_debug = DebugLog(__name__)


class AccountMove(models.Model):
    _inherit = "account.move"

    stock_move_ids = fields.One2many(
        comodel_name="stock.move",
        inverse_name="account_move_id",
        string="Stock Moves",
    )
    stock_valuation_closing_cutoff = fields.Datetime(
        string="Valuation Closing Cutoff",
        copy=False,
        help="The instant this closing entry covered stock moves up to."
        " The next closing starts from here.",
    )
    is_stock_valuation_closing = fields.Boolean(
        string="Inventory Valuation Closing",
        index="btree_not_null",
        copy=False,
        help="Set on the entries generated by the inventory valuation closing."
        " The latest posted one is the cursor the next closing starts from.",
    )

    def _get_lines_onchange_currency(self):
        return self.line_ids.filtered(lambda l: l.display_type != "cogs")

    def copy_data(self, default=None):
        vals_list = super().copy_data(default=default)

        if not self.env.context.get("move_reverse_cancel"):
            for vals in vals_list:
                if "line_ids" in vals:
                    vals["line_ids"] = [
                        line_vals
                        for line_vals in vals["line_ids"]
                        if line_vals[0] != 0
                        or line_vals[2].get("display_type") != "cogs"
                    ]
        return vals_list

    def _post_entries(self):

        _debug.pipeline("stock_entries_post", entries=self)
        if self.env.context.get("move_reverse_cancel"):
            return super()._post_entries()

        self.env["account.move.line"].create(
            self._stock_account_prepare_realtime_out_lines_vals()
        )

        res = super()._post_entries()

        self.line_ids._get_stock_moves().filtered(
            lambda m: m.is_in or m.is_dropship
        )._set_value()

        return res

    def action_draft(self):
        _debug.lifecycle("stock_entry_to_draft", entries=self)
        res = super().action_draft()

        with self.env.protecting(
            self.env["account.move"]._get_field_protections({}, self)
        ):
            self.mapped("line_ids").filtered(
                lambda line: line.display_type == "cogs"
            ).unlink()
        return res

    def action_cancel(self):
        _debug.lifecycle("stock_entry_cancel", entries=self)
        res = super().action_cancel()

        self.mapped("line_ids").filtered(
            lambda line: line.display_type == "cogs"
        ).unlink()
        return res

    def _stock_account_prepare_realtime_out_lines_vals(self):
        _debug.pipeline("anglo_saxon_out_lines_prepare", entries=self)
        lines_vals_list = []

        price_unit_prec = self.env["decimal.precision"].get_precision("Product Price")
        for move in self:
            move = move.with_company(move.company_id)

            if not move.is_sale_document(include_receipts=True):
                continue

            anglo_saxon_price_ctx = move._get_anglo_saxon_price_ctx()

            for line in move.invoice_line_ids:
                if (
                    not line._is_eligible_for_stock_account()
                    or line.product_id.valuation != "real_time"
                ):
                    continue
                accounts = line.product_id.product_tmpl_id._get_product_accounts(
                    fiscal_pos=move.fiscal_position_id
                )
                stock_account = accounts["stock_valuation"]
                credit_expense_account = (
                    accounts["expense"] or move.journal_id.default_account_id
                )
                if not stock_account or not credit_expense_account:
                    continue

                sign = -1 if move.move_type == "out_refund" else 1
                price_unit = line.with_context(anglo_saxon_price_ctx)._get_cogs_value()
                amount_currency = (
                    sign
                    * line.product_uom_id._get_quantity_in_unit(
                        line.quantity, line.product_id.uom_id
                    )
                    * price_unit
                )

                if move.currency_id.is_zero(amount_currency) or float_is_zero(
                    price_unit, precision_digits=price_unit_prec
                ):
                    continue

                lines_vals_list.append(
                    {
                        "name": line.name[:64] if line.name else "",
                        "move_id": move.id,
                        "partner_id": move.commercial_partner_id.id,
                        "product_id": line.product_id.id,
                        "product_uom_id": line.product_uom_id.id,
                        "quantity": line.quantity,
                        "price_unit": price_unit,
                        "amount_currency": -amount_currency,
                        "account_id": stock_account.id,
                        "analytic_distribution": line.analytic_distribution,
                        "display_type": "cogs",
                        "tax_ids": [],
                        "cogs_origin_id": line.id,
                    }
                )

                lines_vals_list.append(
                    {
                        "name": line.name[:64] if line.name else "",
                        "move_id": move.id,
                        "partner_id": move.commercial_partner_id.id,
                        "product_id": line.product_id.id,
                        "product_uom_id": line.product_uom_id.id,
                        "quantity": line.quantity,
                        "price_unit": -price_unit,
                        "amount_currency": amount_currency,
                        "account_id": credit_expense_account.id,
                        "analytic_distribution": line.analytic_distribution,
                        "display_type": "cogs",
                        "tax_ids": [],
                        "cogs_origin_id": line.id,
                    }
                )
        return lines_vals_list

    def _get_anglo_saxon_price_ctx(self):
        return self.env.context

    def _stock_account_get_last_step_stock_moves(self):
        return self.env["stock.move"]

    def _prepare_invoice_lot_rows(self):
        return []
