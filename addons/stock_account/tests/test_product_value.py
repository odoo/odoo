from datetime import timedelta
from freezegun import freeze_time

from odoo.fields import Datetime

from odoo.addons.stock_account.tests.common import TestStockValuationCommon


class TestProductValue(TestStockValuationCommon):
    _test_user_groups = (
        'stock.group_stock_manager',  # stock.move/quant/location/picking(.type) are the subject of valuation tests
        'product.group_product_manager',  # product.product/template/category/attribute create/write are the subject
        'account.group_account_manager',  # subject: mrp.account.wip.accounting wizard (test_wip_accounting_00)
        'account.group_account_invoice',  # account.move (bills/invoices/COGS) generated by valuation are asserted here
    )

    _test_user_name = 'Test User'

    def test_average_real_time(self):

        product = self.product_avco_auto

        with freeze_time(Datetime.now()) as frozen:

            # add 10 in stock, standard_price at 10
            self.env['stock.quant'].create([{
                'product_id': product.id,
                'location_id': self.warehouse.lot_stock_id.id,
                'inventory_quantity': 10,
            }]).action_apply_inventory()
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # change standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv1 = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 200.0)

            # receive 10 at 30
            frozen.tick(timedelta(seconds=1))
            m_in = self._make_in_move(product, 10, 30)
            self.assertEqual(product.standard_price, 25.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 500.0)

            # deliver 1
            frozen.tick(timedelta(seconds=1))
            m_out = self._make_out_move(product, 1)
            self.assertEqual(m_out.value, -25.0)
            self.assertEqual(product.standard_price, 25.0)
            self.assertEqual(product.qty_available, 19)
            self.assertEqual(product.total_value, 475.0)

            # change reception value to 400
            frozen.tick(timedelta(seconds=1))
            m_in.value_manual = 400
            self.assertEqual(m_out.value, -30.0)
            self.assertEqual(product.standard_price, 30.0)
            self.assertEqual(product.qty_available, 19)
            self.assertEqual(product.total_value, 570.0)

            # change standard_price to 40
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 40
            pv2 = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 40.0)
            self.assertEqual(product.qty_available, 19)
            self.assertEqual(product.total_value, 760.0)

            # change first product_value to 10
            frozen.tick(timedelta(seconds=1))
            pv1.new_cost = 10
            self.assertEqual(m_out.value, -25.0)
            self.assertEqual(pv2.old_cost, 25.0)

            self.assertEqual(product.standard_price, 40.0)
            self.assertEqual(product.qty_available, 19)
            self.assertEqual(product.total_value, 760.0)

    def test_average_real_time_lot(self):

        product = self.product_avco_auto
        product.store_by = "lot"
        product.lot_valuated = True

        lot1 = self.env["stock.lot"].create({"name": "lot1", "product_id": product.id})
        lot2 = self.env["stock.lot"].create({"name": "lot2", "product_id": product.id})
        lot3 = self.env["stock.lot"].create({"name": "lot3", "product_id": product.id})
        lot4 = self.env["stock.lot"].create({"name": "lot4", "product_id": product.id})

        with freeze_time(Datetime.now()) as frozen:

            # receive 10 lot1 & 10 lot2, standard_price at 10
            self._make_in_move(product, 10, 10, lot_ids=[lot1])
            m_in2 = self._make_in_move(product, 10, 10, lot_ids=[lot2])
            self.assertEqual(product.total_value, 200.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.standard_price, 10.0)

            # change lot2's move value to 200
            frozen.tick(timedelta(seconds=1))
            m_in2.value_manual = 200
            self.assertEqual(lot1.standard_price, 10.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(product.total_value, 300.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.standard_price, 15.0)

            # take 2 time slots to backdate receptions later
            frozen.tick(timedelta(seconds=1))
            t1 = Datetime.now()
            frozen.tick(timedelta(seconds=1))
            t2 = Datetime.now()

            # change product standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(lot1.standard_price, 20.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(product.total_value, 400.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.standard_price, 20.0)

            # receive 10 lot3 & 10 lot4
            frozen.tick(timedelta(seconds=1))
            m_in3 = self._make_in_move(product, 10, 10, lot_ids=[lot3])
            frozen.tick(timedelta(seconds=1))
            m_in4 = self._make_in_move(product, 10, 10, lot_ids=[lot4])
            self.assertEqual(lot1.standard_price, 20.0)
            self.assertEqual(lot1.total_value, 200.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(lot2.total_value, 200.0)
            self.assertEqual(lot3.standard_price, 10.0)
            self.assertEqual(lot3.total_value, 100.0)
            self.assertEqual(lot4.standard_price, 10.0)
            self.assertEqual(lot4.total_value, 100.0)
            self.assertEqual(product.total_value, 600.0)
            self.assertEqual(product.qty_available, 40)
            self.assertEqual(product.standard_price, 15.0)  # 600 / 40

            # deliver 1 lot3
            frozen.tick(timedelta(seconds=1))
            m_out = self._make_out_move(product, 1, lot_ids=[lot3])
            self.assertEqual(m_out.value, -10.0)
            self.assertEqual(lot1.standard_price, 20.0)
            self.assertEqual(lot1.total_value, 200.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(lot2.total_value, 200.0)
            self.assertEqual(lot3.standard_price, 10.0)
            self.assertEqual(lot3.total_value, 100.0 - 10.0)
            self.assertEqual(lot4.standard_price, 10.0)
            self.assertEqual(lot4.total_value, 100.0)
            self.assertEqual(product.total_value, 590.0)
            self.assertEqual(product.qty_available, 39)
            self.assertEqual(product.standard_price, 15.13)

            # backdate lot3's reception
            frozen.tick(timedelta(seconds=1))
            m_in3.picking_id.action_toggle_is_locked()
            m_in3.picking_id.date_done = t1
            self.assertEqual(m_out.value, -20.0)
            self.assertEqual(lot1.standard_price, 20.0)
            self.assertEqual(lot1.total_value, 200.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(lot2.total_value, 200.0)
            self.assertEqual(lot3.standard_price, 20.0)
            self.assertEqual(lot3.total_value, 200.0 - 20.0)
            self.assertEqual(lot4.standard_price, 10.0)
            self.assertEqual(lot4.total_value, 100.0)
            self.assertEqual(product.total_value, 680.0)
            self.assertEqual(product.qty_available, 39)
            self.assertEqual(product.standard_price, 17.44)

            # backdate lot4's reception
            frozen.tick(timedelta(seconds=1))
            m_in4.picking_id.action_toggle_is_locked()
            m_in4.picking_id.date_done = t2
            self.assertEqual(m_out.value, -20.0)
            self.assertEqual(lot1.standard_price, 20.0)
            self.assertEqual(lot1.total_value, 200.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(lot2.total_value, 200.0)
            self.assertEqual(lot3.standard_price, 20.0)
            self.assertEqual(lot3.total_value, 200.0 - 20.0)
            self.assertEqual(lot4.standard_price, 20.0)
            self.assertEqual(lot4.total_value, 200.0)
            self.assertEqual(product.total_value, 780.0)
            self.assertEqual(product.qty_available, 39)
            self.assertEqual(product.standard_price, 20.0)

            # change lot3 standard_price to 30
            lot3.standard_price = 30
            self.assertEqual(lot3.standard_price, 30.0)
            self.assertEqual(lot3.total_value, 270.0)

            # unlink product_value pv
            pv.unlink()
            self.assertEqual(m_out.value, -10.0)
            self.assertEqual(lot1.standard_price, 10.0)
            self.assertEqual(lot1.total_value, 100.0)
            self.assertEqual(lot2.standard_price, 20.0)
            self.assertEqual(lot2.total_value, 200.0)
            self.assertEqual(lot3.standard_price, 30.0)
            self.assertEqual(lot3.total_value, 270.0)
            self.assertEqual(lot4.standard_price, 10.0)
            self.assertEqual(lot4.total_value, 100.0)
            self.assertEqual(product.total_value, 670.0)
            self.assertEqual(product.qty_available, 39)
            self.assertEqual(product.standard_price, 17.18)

    def test_backdate_product_value_1(self):

        product = self.product_avco_auto

        with freeze_time(Datetime.now()) as frozen:

            # add 10 in stock, standard_price at 10
            self.env['stock.quant'].create([{
                'product_id': product.id,
                'location_id': self.warehouse.lot_stock_id.id,
                'inventory_quantity': 10,
            }]).action_apply_inventory()
            m_inventory = self.env["stock.move"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # take time slot to backdate product value later
            frozen.tick(timedelta(seconds=1))
            t = Datetime.now()

            # receive 10 at 15
            frozen.tick(timedelta(seconds=1))
            m_receipt = self._make_in_move(product, 10, 15)
            self.assertEqual(product.standard_price, 12.5)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 250.0)

            # change standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 400.0)

            # backdate product_value changing standard_price to 20
            frozen.tick(timedelta(seconds=1))
            pv.date = t

            self.assertEqual(product.standard_price, 17.5)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 350.0)

            self.assertEqual(m_inventory.value, 200.0)
            self.assertEqual(m_inventory.remaining_value, 175.0)

            self.assertEqual(m_receipt.value, 150.0)
            self.assertEqual(m_receipt.remaining_value, 175.0)

