from datetime import timedelta
from freezegun import freeze_time

from odoo.fields import Datetime

from odoo.addons.stock_account.tests.common import TestStockValuationCommon


class TestProductValue(TestStockValuationCommon):
    _test_user_groups = (
        'stock.group_stock_manager',  # stock.move/quant/location/picking(.type) are the subject of valuation tests
        'product.group_product_manager',  # product.product/template/category/attribute create/write are the subject
        'account.group_account_manager',  # subject: mrp.account.wip.accounting wizard (test_wip_accounting_00)
        'account.group_account_invoice',  # account.move (bills/invoices/COGS) generated by valuation are asserted here
    )

    _test_user_name = 'Test User'

    def test_product_value(self):

        product = self.product_avco_auto

        with freeze_time(Datetime.now()) as frozen:

            # receive 10 at 10
            frozen.tick(timedelta(seconds=1))
            m_in = self._make_in_move(product, 10, 10)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # deliver 1
            frozen.tick(timedelta(seconds=1))
            m_out = self._make_out_move(product, 1)
            self.assertEqual(m_out.value, -10.0)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 9)
            self.assertEqual(product.total_value, 90.0)

            # change reception value to 200
            frozen.tick(timedelta(seconds=1))
            m_in.value_manual = 200
            self.assertEqual(m_out.value, -20.0)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 9)
            self.assertEqual(product.total_value, 180.0)

            # change standard_price to 30
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 30
            self.assertEqual(product.standard_price, 30.0)
            self.assertEqual(product.qty_available, 9)
            self.assertEqual(product.total_value, 270.0)

    def test_unlink_product_value(self):

        product = self.product_avco_auto

        with freeze_time(Datetime.now()) as frozen:

            # receive 10 at 10
            frozen.tick(timedelta(seconds=1))
            self._make_in_move(product, 10, 10)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # change standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 200.0)

            # receive 10 at 20
            frozen.tick(timedelta(seconds=1))
            self._make_in_move(product, 10, 20)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 400.0)

            # unlink product value
            pv.unlink()

            self.assertEqual(product.standard_price, 15.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 300.0)

    def test_backdate_product_value(self):

        product = self.product_avco_auto

        with freeze_time(Datetime.now()) as frozen:

            # add 10 in stock, standard_price at 10
            self.env['stock.quant'].create([{
                'product_id': product.id,
                'location_id': self.warehouse.lot_stock_id.id,
                'inventory_quantity': 10,
            }]).action_apply_inventory()
            m_inventory = self.env["stock.move"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # take time slot to backdate product value later
            frozen.tick(timedelta(seconds=1))
            t = Datetime.now()

            # receive 10 at 15
            frozen.tick(timedelta(seconds=1))
            m_receipt = self._make_in_move(product, 10, 15)
            self.assertEqual(product.standard_price, 12.5)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 250.0)

            # change standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 400.0)

            # backdate product_value changing standard_price to 20
            frozen.tick(timedelta(seconds=1))
            pv.date = t

            self.assertEqual(product.standard_price, 17.5)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 350.0)

            self.assertEqual(m_inventory.value, 200.0)
            self.assertEqual(m_inventory.remaining_value, 175.0)

            self.assertEqual(m_receipt.value, 150.0)
            self.assertEqual(m_receipt.remaining_value, 175.0)

    def test_backdate_product_value_lot(self):

        product = self.product_avco_auto
        product.store_by = "lot"
        product.lot_valuated = True

        lot = self.env["stock.lot"].create({"name": "lot", "product_id": product.id})

        with freeze_time(Datetime.now()) as frozen:

            # receive 10 at 10
            frozen.tick(timedelta(seconds=1))
            m_receipt = self._make_in_move(product, 10, 10, lot_ids=[lot])
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 10)
            self.assertEqual(product.total_value, 100.0)

            # take time slot to backdate product value later
            frozen.tick(timedelta(seconds=1))
            t = Datetime.now()

            # add 10 in stock
            self.env['stock.quant'].create([{
                'product_id': product.id,
                'lot_id': lot.id,
                'location_id': self.warehouse.lot_stock_id.id,
                'inventory_quantity': 10,
            }]).action_apply_inventory()
            m_inventory = self.env["stock.move"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 10.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 200.0)

            # change standard_price to 20
            frozen.tick(timedelta(seconds=1))
            product.standard_price = 20
            pv = self.env["product.value"].search([("product_id", "=", product.id)], order="id desc", limit=1)
            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 400.0)

            # backdate product_value changing standard_price to 20
            frozen.tick(timedelta(seconds=1))
            pv.date = t

            self.assertEqual(product.standard_price, 20.0)
            self.assertEqual(product.qty_available, 20)
            self.assertEqual(product.total_value, 400.0)

            self.assertEqual(m_receipt.value, 100.0)
            self.assertEqual(m_receipt.remaining_value, 200.0)

            self.assertEqual(m_inventory.value, 200.0)
            self.assertEqual(m_inventory.remaining_value, 200.0)
