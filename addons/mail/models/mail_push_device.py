import json
import logging as logger
import secrets
from datetime import timedelta

from requests import Session

from odoo import api, fields, models
from ..tools.jwt import generate_vapid_keys, InvalidVapidError
from ..tools.web_push import (
    ENCRYPTION_BLOCK_OVERHEAD,
    ENCRYPTION_HEADER_SIZE,
    MAX_PAYLOAD_SIZE,
    DeviceUnreachableError,
    push_to_end_point,
)

_logger = logger.getLogger(__name__)

MAX_DIRECT_PUSH = 5
# Access token lifetime: short-lived, stored in the service worker's IndexedDB.
_ACCESS_TOKEN_LIFETIME = timedelta(hours=1)
# Refresh token lifetime: long-lived, stored in an HttpOnly cookie by the browser.
_REFRESH_TOKEN_LIFETIME = timedelta(days=30)


class MailPushDevice(models.Model):
    _name = 'mail.push.device'
    _description = "Push Notification Device"

    partner_id = fields.Many2one(
        'res.partner', string='Partner', index=True, required=True,
        default=lambda self: self.env.user.partner_id)
    endpoint = fields.Char(string='Browser endpoint', required=True)
    keys = fields.Char(string='Browser keys', required=True,
                       help=("It's refer to browser keys used by the notification: \n"
                             "- p256dh: It's the subscription public key generated by the browser. The browser will \n"
                             "          keep the private key secret and use it for decrypting the payload\n"
                             "- auth: The auth value should be treated as a secret and not shared outside of Odoo"))
    expiration_time = fields.Datetime(string='Expiration Token Date')
    token = fields.Char(
        string='Access Token',
        copy=False,
        help="Short-lived access token (1 hour) stored in the service worker's IndexedDB. "
             "Used to refresh the push subscription endpoint without requiring an active "
             "login session.",
    )
    token_expiry = fields.Datetime(
        string='Access Token Expiry',
        copy=False,
        help="Expiry datetime for the access token. After this the service worker must "
             "use the refresh token to obtain a new access token.",
    )
    refresh_token = fields.Char(
        string='Refresh Token',
        copy=False,
        groups='base.no_one',
        help="Long-lived one-time-use token (30 days) stored in an HttpOnly cookie by the "
             "browser. Exchanged for a new access + refresh token pair when the access token "
             "expires, without requiring a full login session.",
    )
    refresh_token_expiry = fields.Datetime(
        string='Refresh Token Expiry',
        copy=False,
        groups='base.no_one',
    )

    _endpoint_unique = models.Constraint(
        'unique(endpoint)',
        'The endpoint must be unique !',
    )

    def _issue_tokens(self):
        """Issue a fresh access token (1 h) and refresh token (30 d).

        Writes the new tokens and expiry dates to self. Returns the plain-text
        values so the calling controller can forward them to the client.

        :returns: {'access_token': str, 'refresh_token': str}
        :rtype: dict
        """
        now = fields.Datetime.now()
        access_token = secrets.token_urlsafe(32)
        refresh_token_val = secrets.token_urlsafe(32)
        self.write({
            'token': access_token,
            'token_expiry': now + _ACCESS_TOKEN_LIFETIME,
            'refresh_token': refresh_token_val,
            'refresh_token_expiry': now + _REFRESH_TOKEN_LIFETIME,
        })
        return {'access_token': access_token, 'refresh_token': refresh_token_val}

    @api.model
    def get_web_push_vapid_public_key(self):
        ir_params_sudo = self.env['ir.config_parameter'].sudo()
        public_key = 'mail.web_push_vapid_public_key'
        public_key_value = ir_params_sudo.get_str(public_key)
        # Regenerate new Keys if public key not present
        if not public_key_value:
            self.sudo().search([]).unlink()  # Reset all devices (ServiceWorker)
            private_key_value, public_key_value = generate_vapid_keys()
            ir_params_sudo.set_str('mail.web_push_vapid_private_key', private_key_value)
            ir_params_sudo.set_str(public_key, public_key_value)
            _logger.info("WebPush: missing public key, new VAPID keys generated")
        return public_key_value

    @api.model
    def register_devices(self, **kw):
        sw_vapid_public_key = kw.get('vapid_public_key')
        valid_sub = self._verify_vapid_public_key(sw_vapid_public_key)
        if not valid_sub:
            raise InvalidVapidError("Invalid VAPID public key")
        endpoint = kw.get('endpoint')
        browser_keys = kw.get('keys')
        if not endpoint or not browser_keys:
            return
        search_endpoint = kw.get('previousEndpoint', endpoint)
        mail_push_device = self.sudo().search([('endpoint', '=', search_endpoint)])
        if mail_push_device:
            if mail_push_device.partner_id != self.env.user.partner_id:
                mail_push_device.write({
                    'endpoint': endpoint,
                    'expiration_time': kw.get('expirationTime'),
                    'keys': json.dumps(browser_keys),
                    'partner_id': self.env.user.partner_id,
                })
        else:
            mail_push_device = self.sudo().create([{
                'endpoint': endpoint,
                'expiration_time': kw.get('expirationTime'),
                'keys': json.dumps(browser_keys),
                'partner_id': self.env.user.partner_id.id,
            }])
        tokens = mail_push_device._issue_tokens()
        return {'token': tokens['access_token'], 'refresh_token': tokens['refresh_token']}

    @api.model
    def unregister_devices(self, **kw):
        endpoint = kw.get('endpoint')
        if not endpoint:
            return
        mail_push_device = self.sudo().search([
            ('endpoint', '=', endpoint)
        ])
        if mail_push_device:
            mail_push_device.unlink()

    @api.model
    def refresh_subscription_by_token(self, token, endpoint, keys, vapid_public_key,
                                      previous_endpoint=None, expiration_time=None):
        """Update a push subscription without a user session.

        Called by the service worker's pushsubscriptionchange handler via
        POST /web/push/device/refresh. The device is looked up by its previous
        endpoint (a non-secret URL) and the access token is verified using
        secrets.compare_digest() to prevent timing side-channels.

        On success the access token is rotated (new 1-hour credential) and the
        new value is returned so the service worker can update its IndexedDB copy.

        :param str token: access token from the service worker's IndexedDB
        :param str endpoint: new push subscription endpoint URL
        :param dict keys: new push subscription keys (p256dh, auth)
        :param str vapid_public_key: server VAPID public key (cross-check)
        :param str previous_endpoint: old endpoint used to locate the device record
        :param expiration_time: optional new expiration timestamp
        :returns: {'success': True, 'token': new_token},
            {'success': False, 'reason': 'expired'} if the access token is expired,
            or {'success': False} on any other failure
        :rtype: dict
        """
        if not self._verify_vapid_public_key(vapid_public_key):
            return {'success': False}
        search_endpoint = previous_endpoint or endpoint
        mail_push_device = self.sudo().search([('endpoint', '=', search_endpoint)], limit=1)
        if not mail_push_device:
            return {'success': False}
        # Verify the token with a constant-time comparison to prevent timing attacks.
        if not secrets.compare_digest(mail_push_device.token or '', token or ''):
            return {'success': False}
        # Only reveal 'expired' once the token identity has been confirmed.
        if mail_push_device.token_expiry and mail_push_device.token_expiry < fields.Datetime.now():
            return {'success': False, 'reason': 'expired'}
        # Update subscription and rotate access token atomically.
        new_access_token = secrets.token_urlsafe(32)
        mail_push_device.write({
            'endpoint': endpoint,
            'keys': json.dumps(keys),
            'expiration_time': expiration_time,
            'token': new_access_token,
            'token_expiry': fields.Datetime.now() + _ACCESS_TOKEN_LIFETIME,
        })
        return {'success': True, 'token': new_access_token}

    @api.model
    def _rotate_tokens(self, refresh_token, previous_endpoint=None):
        """Issue a new access + refresh token pair in exchange for a valid refresh token.

        Called by POST /web/push/device/token/rotate when the service worker's
        access token has expired. The refresh token value is read from the HttpOnly
        cookie by the controller and passed here.

        The old refresh token is immediately invalidated (one-time use) and a new
        pair is written atomically before the response is sent.

        :param str refresh_token: current refresh token from the HttpOnly cookie
        :param str previous_endpoint: current device endpoint for record lookup
        :returns: {'access_token': str, 'refresh_token': str} or ``None`` on failure
        :rtype: dict or None
        """
        if not refresh_token or not previous_endpoint:
            return None
        device = self.sudo().search([('endpoint', '=', previous_endpoint)], limit=1)
        if not device or not device.refresh_token:
            return None
        # Constant-time comparison to prevent timing attacks on the refresh token.
        if not secrets.compare_digest(device.refresh_token, refresh_token):
            return None
        if device.refresh_token_expiry and device.refresh_token_expiry < fields.Datetime.now():
            return None
        tokens = device._issue_tokens()
        return {'access_token': tokens['access_token'], 'refresh_token': tokens['refresh_token']}

    def _verify_vapid_public_key(self, sw_public_key):
        ir_params_sudo = self.env['ir.config_parameter'].sudo()
        db_public_key = ir_params_sudo.get_str('mail.web_push_vapid_public_key')
        return db_public_key == sw_public_key

    def _web_push_get_partners_parameters(self, partner_ids):
        """
        :param partner_ids: IDs of the res.partners
        :returns: the `mail.push.device` records, the vapid private key and the vapid public key
        """
        # sudo: mail.push.device - can read the devices of the notified partners to send them a push
        devices_su = self.sudo()
        if not partner_ids:
            return devices_su, None, None
        # sudo: ir.config_parameter - read keys are hard-coded and the private key only signs the push
        vapid_private_key = self.env["ir.config_parameter"].sudo().get_str("mail.web_push_vapid_private_key")
        vapid_public_key = self.env["ir.config_parameter"].sudo().get_str("mail.web_push_vapid_public_key")
        if not vapid_private_key or not vapid_public_key:
            return devices_su, None, None
        return devices_su.search([("partner_id", "in", partner_ids)]), vapid_private_key, vapid_public_key

    def _web_push_send_notification(self, private_key, public_key, payload_by_lang=None, payload=None, force_direct_send=False):
        """Send a push notification to these devices.

        :param payload: JSON serializable dict following the notification API specs (https://notifications.spec.whatwg.org/#api)
        :param payload_by_lang: a dict mapping payload by lang, either this or payload must be provided
        :param force_direct_send: push to the endpoints from the current request
          instead of queuing ``mail.push`` records for the cron once more than
          ``MAX_DIRECT_PUSH`` devices are targeted. Endpoints are then contacted
          one after the other, hence only for notifications that cannot wait for
          the cron (e.g. an incoming call) and on few devices.
        """
        if len(self) < MAX_DIRECT_PUSH or force_direct_send:
            session = Session()
            devices_to_unlink = set()
            for device in self:
                try:
                    push_to_end_point(
                        base_url=self.browse().get_base_url(),
                        device={
                            'id': device.id,
                            'endpoint': device.endpoint,
                            'keys': device.keys
                        },
                        payload=json.dumps(payload_by_lang and payload_by_lang[device.partner_id.lang] or payload),
                        vapid_private_key=private_key,
                        vapid_public_key=public_key,
                        session=session,
                    )
                except DeviceUnreachableError:
                    devices_to_unlink.add(device.id)
                except Exception as e:  # noqa: BLE001
                    # Avoid blocking the whole request just for a notification
                    _logger.error('An error occurred while contacting the endpoint: %s', e)

            # clean up obsolete devices
            if devices_to_unlink:
                devices_list = list(devices_to_unlink)
                # sudo: mail.push.device - can unlink the devices whose endpoint is gone
                self.env['mail.push.device'].sudo().browse(devices_list).unlink()

        else:
            # sudo: mail.push - can create the pushes of these devices for the cron to send them
            self.env['mail.push'].sudo().create([{
                'mail_push_device_id': device.id,
                'payload': json.dumps(payload_by_lang and payload_by_lang[device.partner_id.lang] or payload),
            } for device in self])
            self.env.ref('mail.ir_cron_web_push_notification')._trigger()

    def _web_push_truncate_payload(self, payload):
        r"""Check the payload limit of ~3990 bytes to avoid 413 error return code.

        See `_truncate_payload_get_max_payload_length` for the exact limit.

        When sending a push notification, the entire encrypted json payload should be no more than 4096 bytes in length.
        To ensure this, when possible, the body contents of the notification are truncated in such a way that the end
        result will not exceed that limit.

        Example Truncation:
            We know there is an encryption overhead of 10 bytes, and a total limit of 50 bytes.
            The payload is `{"messageId": "5291", "body": "A very long text"}`
            So we have an effective payload length of (50 - 10) = 40.
            Our full payload is 49 bytes, of which 16 bytes are text we are willing to truncate.
            We must remove 9 bytes, such that the payload becomes effectively
            `{"messageId": "5291", "body": "A very "}`

        There are some considerations with this approach. Notably we must consider the full encoded length in bytes.
        While we encode the payload in utf-8, it is actually transformed into json with `ensure_ascii=True` first.
        This means this payload, as a python dictionary: {"body": "BØDY"}; Becomes {"body": "B\\u00d8DY"}.
        Where `00d8` is the unicode codepoint for "Ø", and "\\u" is a json escape sequence.

        In that case we must ensure that the truncated body does not suddenly contain invalid unicode escape sequences.
        Similarly to how one should not cut an encoded string in the middle of a utf-8 character.

        Example Unicode Truncation:
            Assume {"body": "BØDY"} needs to be truncated of 3 bytes
            It should not become {"body": "B\\u00d"}
            Instead it should become {"body": "B"}

        :param dict payload: Current payload to truncate.
        :return: The truncated payload;
        """
        payload_length = len(json.dumps(payload).encode())
        # json.dumps defaults to translating unicode to hex codepoints (ensure_ascii=True)
        # hence we need to check the length the body takes up in that format
        # json string quotes are removed and the body is not encoded as it's already all ASCII
        body = json.dumps(payload['options']['body'])[1:-1]
        body_length = len(body)

        max_length = self._truncate_payload_get_max_payload_length()
        if payload_length > max_length:
            body_max_length = max(0, max_length - payload_length + body_length)
            # truncate to max length and try to loads again
            # if there's any error, it will be a unicode error
            # the error position gives us the start of the codepoint
            # remove everything after that + the preceding escape marker (\u)
            try:
                # remove trailing '\' as the error for that is unhelpful
                truncated_body = body[:body_max_length].rstrip('\\')
                truncated_body = json.loads(f'"{truncated_body}"')
            except json.decoder.JSONDecodeError as json_error:
                truncated_body = json.loads(f'"{body[:json_error.pos - 2]}"')
            payload['options']['body'] = truncated_body
        return payload

    @staticmethod
    def _truncate_payload_get_max_payload_length():
        """Define the maximum length we want for the payload.

        This limit is derived from:

            - the maximum encrypted payload size we may send to web push servers.
            - the header required using AES128GCM encryption.
            - the overhead of encrypting one block. Payload will not exceed 1 block as the point
              here is to keep everything within the default (and max) block size.

        For details about encryption overhead sizes, see variable definition in web_push.
        Currently all of these values are payload-independent.
        """
        return MAX_PAYLOAD_SIZE - ENCRYPTION_HEADER_SIZE - ENCRYPTION_BLOCK_OVERHEAD
