from odoo import api, fields, models


class CustomPayrollSlipDetail(models.Model):
    _name = 'custom.payroll.slip.detail'
    _description = 'Payslip Detail Component'

    slip_gaji_id = fields.Many2one('custom.payroll.slip', string='Payslip', required=True, ondelete='cascade')
    component_type = fields.Selection(
        selection=[
            ('gaji_pokok', 'Basic Salary'),
            ('tunjangan', 'Allowance'),
            ('potongan', 'Deduction'),
            ('lembur', 'Overtime'),
            ('bpjs', 'BPJS'),
            ('rule', 'Salary Rule'),
            ('lainnya', 'Others'),
        ],
        string='Component Type',
        required=True,
        default='tunjangan',
    )
    tunjangan_id = fields.Many2one('custom.payroll.tunjangan', string='Allowance')
    bpjs_id = fields.Many2one('custom.payroll.bpjs', string='BPJS')
    potongan_tetap_id = fields.Many2one(
        'custom.payroll.potongan.tetap',
        string='Fixed Deduction',
        help='Set automatically when this line is generated from a fixed deduction master.',
    )
    rule_id = fields.Many2one(
        'custom.payroll.rule',
        string='Salary Rule',
        help='Set automatically when this line is generated by a salary rule.',
    )
    nominal = fields.Monetary(
        string='Amount',
        currency_field='currency_id',
        required=True,
        default=0.0,
        help='Nilai komponen. Jika BPJS dipilih dan percentage > 0, '
             'nilai akan otomatis = percentage × gaji pokok. '
             'Setelah payslip dibuat, nilai ini final dan tidak berubah.',
    )
    description = fields.Char(string='Description')
    currency_id = fields.Many2one(related='slip_gaji_id.currency_id', string='Currency')

    @api.onchange('component_type', 'slip_gaji_id')
    def _onchange_overtime(self):
        if self.component_type == 'lembur' and self.slip_gaji_id:
            self.nominal = self.slip_gaji_id.overtime_amount
            self.description = 'Auto Overtime'

    @api.onchange('tunjangan_id')
    def _onchange_tunjangan_id(self):
        if self.tunjangan_id:
            self.nominal = self.tunjangan_id.nilai
            self.description = self.tunjangan_id.name

    @api.onchange('bpjs_id')
    def _onchange_bpjs_id(self):
        if self.bpjs_id:
            if self.bpjs_id.persen and self.slip_gaji_id.total_gaji_pokok:
                self.nominal = self.bpjs_id.persen * self.slip_gaji_id.total_gaji_pokok / 100.0
            else:
                self.nominal = self.bpjs_id.nominal
            self.description = self.bpjs_id.name
