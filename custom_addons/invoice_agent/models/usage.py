"""Token/cost ledger for Claude invoice extractions.

Every successful extraction writes one row here via
``invoice.llm.service.log_usage``. The row carries the raw token counts from
the API response (including prompt-cache read/write tokens) and a ``cost``
computed at Claude Opus 4 rates (see ``llm_service`` price constants). The
grouped list view shows month-to-date AI spend, reusing Odoo's
``read_group`` (%m/ %Y) group-by so no widget is needed.
"""

from odoo import _, api, fields, models

from .llm_service import (
    OPUS_PRICE_PER_MT_CACHE_READ,
    OPUS_PRICE_PER_MT_CACHE_WRITE,
    OPUS_PRICE_PER_MT_INPUT,
    OPUS_PRICE_PER_MT_OUTPUT,
)


class InvoiceAgentUsage(models.Model):
    _name = "invoice.agent.usage"
    _description = "Invoice Agent — per-extraction token and cost ledger"
    _order = "create_date desc, id desc"

    move_id = fields.Many2one(
        comodel_name="account.move",
        string="Invoice",
        ondelete="set null",
        index=True,
        help="The bill this extraction call was for. May be void when the "
        "source bill is later deleted.",
    )
    company_id = fields.Many2one(
        "res.company",
        string="Company",
        required=True,
        default=lambda self: self.env.company,
    )
    model = fields.Char(
        string="Model",
        default="claude-opus-4-8",
        help="Anthropic model id that produced this usage row.",
    )
    input_tokens = fields.Integer(
        string="Input Tokens",
        help="Tokens in the request that were not served from the prompt cache.",
    )
    cache_creation_input_tokens = fields.Integer(
        string="Cache Creation Tokens",
        help="Tokens written to the prompt cache on this call (cold prefix).",
    )
    cache_read_input_tokens = fields.Integer(
        string="Cache Read Tokens",
        help="Tokens served from the prompt cache (a hit: non-zero only when "
        "the 4096+ token prefix is byte-identical to the previous call).",
    )
    output_tokens = fields.Integer(
        string="Output Tokens",
        help="Tokens generated by the model in the response.",
    )
    cost = fields.Float(
        string="Cost (USD)",
        compute="_compute_cost",
        store=True,
        readonly=True,
        digits=(16, 4),
        help="Cost of this extraction at Claude Opus 4 rates: cache writes "
        "and reads are billed at 25%% / 10%% of input price respectively.",
    )
    create_date = fields.Datetime(
        string="Created On",
        readonly=True,
        index=True,
        help="Logged when the extraction call returned; indexed so the "
        "month-to-date spend group-by is cheap.",
    )

    @api.depends(
        "input_tokens",
        "cache_creation_input_tokens",
        "cache_read_input_tokens",
        "output_tokens",
    )
    def _compute_cost(self):
        for usage in self:
            usage.cost = (
                (usage.input_tokens or 0) * OPUS_PRICE_PER_MT_INPUT
                + (usage.cache_creation_input_tokens or 0)
                * OPUS_PRICE_PER_MT_CACHE_WRITE
                + (usage.cache_read_input_tokens or 0) * OPUS_PRICE_PER_MT_CACHE_READ
                + (usage.output_tokens or 0) * OPUS_PRICE_PER_MT_OUTPUT
            ) / 1_000_000

    # ------------------------------------------------------------------
    # Month-to-date spend helper (used by the list view group-by and by
    # reporting code)
    # ------------------------------------------------------------------
    @api.model
    def mtd_spend(self):
        """Total AI spend in the current calendar month (USD)."""
        domain = [
            ("create_date", ">=", fields.Date.context_today(self).replace(day=1)),
        ]
        return sum(self.search(domain).mapped("cost"))

    def name_get(self):
        """Short human label: '<total tokens> tokens · $<cost>'."""
        result = []
        for usage in self:
            total = (
                (usage.input_tokens or 0)
                + (usage.output_tokens or 0)
                + (usage.cache_read_input_tokens or 0)
                + (usage.cache_creation_input_tokens or 0)
            )
            result.append(
                (
                    usage.id,
                    _("%(count)d tokens · $%(cost).4f", count=total, cost=usage.cost),
                ),
            )
        return result

    _sql_constraints = [
        (
            "check_usage_tokens_non_negative",
            (
                "CHECK(input_tokens >= 0 AND output_tokens >= 0 AND "
                "cache_creation_input_tokens >= 0 AND cache_read_input_tokens >= 0)"
            ),  # noqa: E501
            "Token counts must not be negative.",
        ),
    ]
