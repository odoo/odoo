from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from odoo.libs.debug_log import DebugLog

from .schema import SCHEMA_PATH, AttrType, Schema, schema

_debug = DebugLog(__name__)

REPO_ROOT = Path(__file__).resolve().parents[3]
DTS_PATH = REPO_ROOT / "addons/web/static/src/views/ir/view_ir_schema.d.ts"
JSON_SCHEMA_PATH = SCHEMA_PATH.with_name("view_ir.schema.json")
HEADER = "generated by `python -m odoo.tools.view_ir._generate` from odoo/tools/view_ir/schema.json — do not edit"


def _ts_type_name(*parts: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in parts).replace("-", "")


def _ts_key(attr: str) -> str:
    if attr.endswith("-*"):
        return f"[key: `{attr[:-1]}${{string}}`]"
    if attr.isidentifier():
        return f"{attr}?"
    return f'"{attr}"?'


def _ts_attr_value(attr_type: AttrType) -> str:
    if isinstance(attr_type, list):
        return " | ".join(json.dumps(v) for v in attr_type)
    return "string"


def _ts_attrs_interface(name: str, tables: list[dict[str, AttrType]]) -> str:
    merged: dict[str, AttrType] = {}
    for table in reversed(tables):
        merged.update(table)
    fixed = sorted(a for a in merged if not a.endswith("-*"))
    wild = sorted(a for a in merged if a.endswith("-*"))
    lines = [f"export interface {name} {{"]
    lines += [f"    {_ts_key(a)}: {_ts_attr_value(merged[a])};" for a in fixed]
    lines += [f"    {_ts_key(a)}: string;" for a in wild]
    lines.append("}")
    return "\n".join(lines)


def render_dts(spec: Schema) -> str:
    out = [f"// {HEADER}", "", f"export const SCHEMA_VERSION: {spec.version};", ""]
    out.append(
        "export type ViewType = " + " | ".join(json.dumps(t) for t in spec.types) + ";"
    )
    out.append(
        "export type AttrType = "
        + " | ".join(json.dumps(t) for t in spec.attr_types)
        + ";"
    )
    out.append(
        "export type HtmlTag = "
        + " | ".join(json.dumps(t) for t in sorted(spec.html_tags))
        + ";"
    )
    out.append(
        "export type PatchKind = "
        + " | ".join(json.dumps(k) for k in spec.patch_nodes)
        + ";"
    )
    out.append("")
    out.append(
        "export interface ViewIRNode {\n"
        "    kind: string;\n"
        "    attrs?: Record<string, string>;\n"
        "    text?: string;\n"
        "    tail?: string;\n"
        "    nsmap?: Record<string, string>;\n"
        "    children?: ViewIRNode[];\n"
        "}"
    )
    out.append("")
    out.append(_ts_attrs_interface("CommonAttrs", [spec.common_attrs]))
    out.append(_ts_attrs_interface("HtmlAttrs", [spec.html_attrs, spec.common_attrs]))
    out.append(_ts_attrs_interface("PatchAttrs", [spec.patch_attrs]))
    for kind, node in spec.patch_nodes.items():
        out.append(
            _ts_attrs_interface(
                _ts_type_name("patch", kind, "attrs"), [node.attrs, spec.patch_attrs]
            )
        )
    for vtype, vspec in spec.types.items():
        prefix = _ts_type_name(vtype)
        kinds = sorted(vspec.nodes)
        out.append("")
        out.append(
            f"export type {prefix}Kind = "
            + " | ".join(json.dumps(k) for k in kinds)
            + ";"
        )
        out.extend(
            _ts_attrs_interface(
                _ts_type_name(vtype, kind, "attrs"),
                [vspec.nodes[kind].attrs, spec.common_attrs, spec.patch_attrs],
            )
            for kind in kinds
        )
        out.append(f"export interface {prefix}Attrs {{")
        out += [
            f"    {json.dumps(k)}: {_ts_type_name(vtype, k, 'attrs')};" for k in kinds
        ]
        out.append("}")
        out.append(f"export interface {prefix}Children {{")
        for kind in kinds:
            children = vspec.nodes[kind].children
            value = (
                " | ".join(json.dumps(c) for c in sorted(children))
                if children
                else "string"
            )
            out.append(f"    {json.dumps(kind)}: {value};")
        out.append("}")
    out.append("")
    out.append("export interface ViewIRSchema {")
    out += [
        f"    {json.dumps(v)}: {{ root: {json.dumps(s.root)}; attrs: {_ts_type_name(v)}Attrs; children: {_ts_type_name(v)}Children }};"
        for v, s in spec.types.items()
    ]
    out.append("}")
    return "\n".join(out) + "\n"


def _json_value_schema(attr_type: AttrType) -> dict:
    if isinstance(attr_type, list):
        return {"enum": attr_type}
    match attr_type:
        case "bool":
            return {"enum": ["1", "0", "True", "False", "true", "false"]}
        case "int":
            return {"type": "string", "pattern": "^-?[0-9]+$"}
        case _:
            return {"type": "string", "x-odoo-type": attr_type}


def _json_attrs_schema(tables: list[dict[str, AttrType]]) -> dict:
    merged: dict[str, AttrType] = {}
    for table in reversed(tables):
        merged.update(table)
    properties = {
        a: _json_value_schema(t) for a, t in merged.items() if not a.endswith("-*")
    }
    patterns = {
        f"^{a[:-1]}": _json_value_schema(t)
        for a, t in merged.items()
        if a.endswith("-*")
    }
    out: dict = {
        "type": "object",
        "properties": properties,
        "additionalProperties": False,
    }
    if patterns:
        out["patternProperties"] = patterns
    return out


def render_json_schema(spec: Schema) -> dict:
    node_props = {
        "kind": {"type": "string"},
        "attrs": {"type": "object", "additionalProperties": {"type": "string"}},
        "text": {"type": "string"},
        "tail": {"type": "string"},
        "nsmap": {"type": "object", "additionalProperties": {"type": "string"}},
        "children": {"type": "array", "items": {"$ref": "#/$defs/node"}},
    }
    defs: dict = {
        "node": {
            "type": "object",
            "required": ["kind"],
            "properties": node_props,
            "additionalProperties": False,
        }
    }
    html_kinds = sorted(spec.html_tags)
    for vtype, vspec in spec.types.items():
        branches = []
        for kind, node in vspec.nodes.items():
            branches.append(
                {
                    "if": {"properties": {"kind": {"const": kind}}},
                    "then": {
                        "properties": {
                            "attrs": _json_attrs_schema(
                                [node.attrs, spec.common_attrs, spec.patch_attrs]
                            )
                        }
                    },
                }
            )
        for kind, node in spec.patch_nodes.items():
            branches.append(
                {
                    "if": {"properties": {"kind": {"const": kind}}},
                    "then": {
                        "properties": {
                            "attrs": _json_attrs_schema([node.attrs, spec.patch_attrs])
                        }
                    },
                }
            )
        branches.append(
            {
                "if": {"properties": {"kind": {"enum": html_kinds}}},
                "then": {
                    "properties": {
                        "attrs": _json_attrs_schema(
                            [spec.html_attrs, spec.common_attrs, spec.patch_attrs]
                        )
                    }
                },
            }
        )
        defs[vtype] = {
            "type": "object",
            "required": ["kind"],
            "properties": {
                **node_props,
                "kind": {
                    "enum": sorted(vspec.nodes) + list(spec.patch_nodes) + html_kinds
                },
                "children": {"type": "array", "items": {"$ref": f"#/$defs/{vtype}"}},
            },
            "additionalProperties": False,
            "allOf": branches,
        }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"urn:odoo:view-ir:{spec.version}",
        "title": "Odoo view IR",
        "$comment": HEADER,
        "$ref": "#/$defs/node",
        "$defs": defs,
        "x-odoo-roots": {vtype: s.root for vtype, s in spec.types.items()},
    }


def render_json_schema_text(spec: Schema) -> str:
    return json.dumps(render_json_schema(spec), indent=1, ensure_ascii=False) + "\n"


def outputs(spec: Schema | None = None) -> dict[Path, str]:
    spec = spec or schema()
    return {DTS_PATH: render_dts(spec), JSON_SCHEMA_PATH: render_json_schema_text(spec)}


def stale() -> list[Path]:
    stale_paths = [
        path
        for path, content in outputs().items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    for path in stale_paths:
        _debug.logic("stale", path=str(path))
    return stale_paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        for path in stale():
            print(f"stale: {path}")
        return 1 if stale() else 0
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        _debug.lifecycle("generated", path=str(path), chars=len(content))
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
